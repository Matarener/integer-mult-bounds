# JSON certificate (emitcert.py) -> Lean file with `check C = true` by `decide +kernel` (RankNine/T2Close.lean).
# usage: python3 emit_t2lean.py cert.json Name out.lean      Apache-2.0.
import json, sys


DEFS = []


def bt(entries, fmt, name=None, ty="ℕ"):
    """entries: list of (index, value); low bit first; BT.lf only at index 0.  Subtrees with more than 24 entries
    become their own definitions (big nested terms hit maxRecDepth)."""
    if not entries: return "BT.em"
    if len(entries) == 1 and entries[0][0] == 0: return f"(BT.lf {fmt(entries[0][1])})"
    ev = [(i // 2, v) for i, v in entries if i % 2 == 0]
    od = [(i // 2, v) for i, v in entries if i % 2 == 1]
    term = f"(BT.nd {bt(ev, fmt, name and name + '0', ty)} {bt(od, fmt, name and name + '1', ty)})"
    if name is not None and len(entries) > 24:
        DEFS.append(f"def {name} : BT ({ty}) := {term}")
        return name
    return term


def btdp(entries):
    """BT.dp of the tree `bt` builds from these entries"""
    if not entries or (len(entries) == 1 and entries[0][0] == 0): return 0
    ev = [(i // 2, v) for i, v in entries if i % 2 == 0]
    od = [(i // 2, v) for i, v in entries if i % 2 == 1]
    return 1 + max(btdp(ev), btdp(od))


GCH = 1500   # stored relations per glue chunk (one big decide over all of them runs out of memory)


def lst(l): return "[" + ", ".join(map(str, l)) + "]"


def clst(l):  # long lists: chunks of 80 joined by ++ (long literals break elaboration)
    if len(l) <= 80: return lst(l)
    return " ++\n  ".join(lst(l[i:i + 80]) for i in range(0, len(l), 80))


def main(src, name, out):
    import gzip
    c = json.load(gzip.open(src, 'rt') if src.endswith('.gz') else open(src))
    num = lambda x: str(x)
    tab = lambda d, dflt, nm: bt(sorted((int(k), v) for k, v in d.items() if v != dflt), num, nm)
    ST = [(i, s) for i, s in enumerate(c['ST']) if s is not None]
    RS = list(enumerate(c['RS']))
    lines = ["import RankNine.T2Glue" if c.get("DESC") else "import RankNine.T2Close", "", "/-! Generated by emit_t2lean.py: exact closure certificate %s -/" % name, "",
             "namespace RankNine.T2.%s" % name, "", "open RankNine.T2", "", "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", ""]
    _t = bt(RS, lst, "tRS_", "List ℕ"); lines += DEFS; DEFS.clear(); lines.append("def RS : BT (List ℕ) := " + _t)
    _t = bt(ST, lst, "tST_", "List ℕ"); lines += DEFS; DEFS.clear(); lines.append("def ST : BT (List ℕ) := " + _t)
    _t = tab(c['OD'], 1000000000, "tOD_"); lines += DEFS; DEFS.clear(); lines.append("def OD : BT ℕ := " + _t)
    _t = tab(c['MK'], 0, "tMK_"); lines += DEFS; DEFS.clear(); lines.append("def MK : BT ℕ := " + _t)
    _t = tab(c['PD'], 1000000000, "tPD_"); lines += DEFS; DEFS.clear(); lines.append("def PD : BT ℕ := " + _t)
    _t = tab(c['PR'], 0, "tPR_"); lines += DEFS; DEFS.clear(); lines.append("def PR : BT ℕ := " + _t)
    _t = tab(c['SG'], 0, "tSG_"); lines += DEFS; DEFS.clear(); lines.append("def SG : BT ℕ := " + _t)
    for nm in ("NE", "GA"):
        l = c[nm]; parts = []
        for j in range(0, max(len(l), 1), 80):
            lines.append(f"def {nm}_{j // 80} : List ℕ := " + lst(l[j:j + 80])); parts.append(f"{nm}_{j // 80}")
        lines.append(f"def {nm} : List ℕ := " + " ++ ".join(parts))
    lines.append(f"def C : Cert := {{ RS := RS, OD := OD, MK := MK, RT := {lst(c['RT'])}, CO := {lst(c['CO'])}, "
                 f"FO := {lst(c['FO'])}, PD := PD, PR := PR, SG := SG, ST := ST, L := {c['L']}, GA := GA, NE := NE, n := {c['n']} }}")
    lines += ["", "theorem check_ok : check C = true := by decide +kernel", ""]
    if c.get("DESC"):
        # descriptors [t, a, s, b, sgn, frame lines...], edge tables, BFS tree with "new endpoint is a row" flags
        DSl = [(i, [d[0], d[1], d[2], d[3], 1 if d[6] > 0 else 0] + list(d[4]) + list(d[5])) for i, d in enumerate(c['DESC'])]
        _t = bt(DSl, lst, "tDS_", "List ℕ"); lines += DEFS; DEFS.clear(); lines.append("def DS : BT (List ℕ) := " + _t)
        EDG = c['EDG']
        _t = bt(sorted((104 * x + y, e) for e, (x, y) in enumerate(EDG) if e != 0), num, "tEI_"); lines += DEFS; DEFS.clear()
        lines.append("def EI : BT ℕ := " + _t)
        _t = bt([(e, x) for e, (x, y) in enumerate(EDG) if x != 0], num, "tER_"); lines += DEFS; DEFS.clear()
        lines.append("def ER : BT ℕ := " + _t)
        _t = bt([(e, y) for e, (x, y) in enumerate(EDG) if y != 0], num, "tEC_"); lines += DEFS; DEFS.clear()
        lines.append("def EC : BT ℕ := " + _t)
        tr = set(c['TREE']); adj = {}
        for e in tr:
            x, y = EDG[e]; adj.setdefault(('r', x), []).append((('c', y), e)); adj.setdefault(('c', y), []).append((('r', x), e))
        seen = {('r', c['ROOT'])}; order = [('r', c['ROOT'])]; T = []
        for v in order:
            for u, e in sorted(adj.get(v, [])):
                if u not in seen: seen.add(u); order.append(u); T.append((e, u[0] == 'r'))
        assert len(T) == len(tr), (len(T), len(tr))
        parts = []
        for j in range(0, max(len(T), 1), 80):
            lines.append(f"def T_{j // 80} : List (ℕ × Bool) := [" + ", ".join(f"({e}, {'true' if b else 'false'})" for e, b in T[j:j + 80]) + "]")
            parts.append(f"T_{j // 80}")
        lines.append("def T : List (ℕ × Bool) := " + " ++ ".join(parts))
        m = sum(1 << r for r in c['ROWS'])
        lines += [f"def m : ℕ := {m}", ""]
        NR = 2 ** max(btdp(list(enumerate(c['RS']))), btdp(DSl))
        lines.append(f"theorem hNR : 2 ^ max C.RS.dp DS.dp = {NR} := by decide +kernel")
        chunks = [(a, min(GCH, NR - a)) for a in range(0, NR, GCH)]
        for i, (a, mm) in enumerate(chunks):
            lines.append(f"theorem g{i} : (List.range' {a} {mm}).all (rsOK C EI ER EC DS {c['E']} m) = true := by decide +kernel")
        lines.append(f"theorem rs_ok : ∀ a < 2 ^ max C.RS.dp DS.dp, rsOK C EI ER EC DS {c['E']} m a = true := by\n  intro a ha\n  rw [hNR] at ha")
        for i, (a, mm) in enumerate(chunks):
            if i < len(chunks) - 1:
                lines.append(f"  by_cases h{i} : a < {a + mm}\n  · exact (rng_all _ {a} {mm}).1 g{i} a (by omega) (by omega)")
            else:
                lines.append(f"  exact (rng_all _ {a} {mm}).1 g{i} a (by omega) (by omega)")
        lines += [f"theorem rest_ok : glueRest C EI ER EC {c['E']} T {c['ROOT']} {c['DIAG0']} = true := by decide +kernel", "",
                  f"theorem glue_ok : glueOK C EI ER EC DS {c['E']} m T {c['ROOT']} {c['DIAG0']} = true :=",
                  f"  glueOK_of C EI ER EC DS {c['E']} m T {c['ROOT']} {c['DIAG0']} rs_ok rest_ok", ""]
    lines += ["end RankNine.T2.%s" % name, ""]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main(*sys.argv[1:4])
