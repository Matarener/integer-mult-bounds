"""Emit ../lean/RankNine/Cert/Fl<k>.lean: the floor for framed type k (T1 Gram + T3 rows/gluing + T3.5 floor_noU).
Reads Cert/Glue<k>.lean (U, O) and chooses a frame f inside Z (reduced) for rows_rep.  Types with a special line
U < 104 use floor_U with G (dead lines s ⊥ U pinning c_U, certificates over Z ∩ O_U ∪ {s}) and BsL = S ∪ {U}.  usage: emit_t3.py k [log.txt]"""
import sys, json, re, time
sys.path.insert(0, '.')
from p104lib import frames, IDX, ORTH, N as NL
from rank_cert import cert, rootv, check
k = int(sys.argv[1]); T0 = time.time()
DROP = {2: 78, 28: 82, 75: 71, 102: 70, 118: 70, 123: 70, 229: 35}
reps = [r for r in json.load(open('orbitsW.json')) if r['frame']]
m = int(reps[k]['mask']); Z = [i for i in range(NL) if m >> i & 1]
if k in DROP: Z = [i for i in Z if i != DROP[k]]
Zs = set(Z)
g = open(f'../lean/RankNine/Cert/Glue{k}.lean').read()
U = int(re.search(r'def U : ℕ := (\d+)', g).group(1))
def log(msg):
    msg = f'[{time.time() - T0:6.1f}s] type {k} {msg}'; print(msg, flush=True)
    if len(sys.argv) > 2: open(sys.argv[2], 'a').write(msg + '\n')
L = lambda xs: '[' + ', '.join(str(x) for x in xs) + ']'
def rc(c):
    X, N_, No, D, pm = c
    return f'⟨{L(X)}, [{", ".join(L(r) for r in N_)}], {L(No)}, {D}, {pm}⟩'
spec = ''
if U < 104:
    O = [v for v in range(NL) if v not in Zs]
    ku = next(i for i in range(9) if rootv(U)[i]); X0 = [x for x in Z if ORTH[x][U]]
    GC = []
    for s_ in O:
        if s_ == U or not ORTH[s_][U]: continue
        c = cert(X0 + [s_], [ku])
        if c is None: continue
        assert check(*c) and all((x in Zs or x == s_) and ORTH[x][U] for x in c[0])
        GC.append((s_, c))
    G = [s_ for s_, _ in GC]
    S = [s_ for s_ in range(NL) if s_ != U and not any(ORTH[s_][v] for v in G)]
    BsL = sorted(S + [U])
    assert len(set(G)) >= 5 and len(BsL) <= 4
    assert all(s_ in BsL or any(ORTH[v][s_] for v in G) for s_ in range(NL))
    gents = ',\n  '.join(f'({s_}, {ku}, {rc(c)})' for s_, c in GC)
    spec = f'''
/-! special line `U = {U}`: {len(G)} pinning lines, `BsL = {BsL}` -/
def GC : List (ℕ × ℕ × RCert) := [
  {gents}]
def G : List ℕ := GC.map (fun e => e.1)
def BsL : List ℕ := {L(BsL)}
theorem hGC : GC.all (fun e => decide (e.1 < 104) && dot e.1 Glue{k}.U == 0 &&
    lcxOK Glue{k}.zm e.1 Glue{k}.U e.2.1 e.2.2) = true := by decide +kernel
theorem hG5 : 5 ≤ (Finset.univ.filter fun v : Fin 104 => (v : ℕ) ∈ G).card := by decide +kernel
theorem hUB : Glue{k}.U ∈ BsL := by decide +kernel
theorem hBs : (Finset.univ.filter fun v : Fin 104 => (v : ℕ) ∈ BsL).card ≤ 4 := by decide +kernel
theorem hcovB : (List.range 104).all (fun s => decide (s ∈ BsL) || G.any (fun v => dot v s == 0)) = true := by
  decide +kernel
theorem hGl : ∀ s ∈ G, s < 104 := by
  intro s hs
  obtain ⟨e, hm, rfl⟩ := List.mem_map.mp hs
  have hc := (List.all_eq_true.mp hGC) e hm
  simp only [Bool.and_eq_true, decide_eq_true_eq] at hc
  exact hc.1.1
'''
TAIL0 = """  exact floor_noU hcap hbic hcensus _ _ _ lam eta (fun v s => by rw [Matrix.of_apply]; exact hrep v s)
    (fun s hs => hcolU s hs (by simp only [Glue{k}.U]; omega)) hrowd (hPs_P104 A B _ f)
    (hglue.imp_right (live_le_four lam _ hin))"""
TAIL1 = """  have hpin : ∀ s ∈ G, lam s = 0 → ∃ b : K, cS A B (gOf A B Step5c{k}.V Step5c{k}.PL Step5c{k}.II Step5c{k}.nV) f Glue{k}.U = b • rho K Glue{k}.U := by
    intro s hs hl
    obtain ⟨e, hm, rfl⟩ := List.mem_map.mp hs
    have hc := (List.all_eq_true.mp hGC) e hm
    simp only [Bool.and_eq_true, decide_eq_true_eq, beq_iff_eq] at hc
    exact hpinT (by norm_num [Glue{k}.U]) e.1 hc.1.1 hl hc.1.2 e.2.1 e.2.2 hc.2
  exact floor_U hcap hbic hcensus _ _ _ lam eta (fun v s => by rw [Matrix.of_apply]; exact hrep v s) Glue{k}.U
    hcolU hrowd (hPs_P104 A B _ f) (hcs_P104 A B _ f) (hglue.imp_right (live_le_four lam _ hin)) G BsL hGl hpin
    hG5 hUB hBs hcovB"""
tail = (TAIL1 if U < 104 else TAIL0).replace('{k}', str(k))
FR = [tuple(IDX[q] for q in f) for f in frames()]
fi = next(i for i, f in enumerate(FR) if all(x in Zs for x in f))
src = f'''import RankNine.Cert.Gram{k}
import RankNine.Cert.Zero{k}
import RankNine.Cert.Glue{k}
import RankNine.Floor

set_option linter.unusedSectionVars false

/-! Floor for framed type {k} (generated by gen/emit_t3.py): frame {fi} = {list(FR[fi])} inside `Z`, special line U = {U}. -/

namespace RankNine.Fl{k}

open Matrix

def f : ℕ := {fi}
theorem hzmeq : Glue{k}.zm = Gram{k}.zm := by decide +kernel
theorem hfin : frInOK (typeMask.getD {k} 0) Glue{k}.zm f = true := by decide +kernel
theorem hfv : fvecOK f = true := by decide +kernel
theorem hzm : (List.range 104).all (fun x => !Glue{k}.zm.testBit x || (typeMask.getD {k} 0).testBit x) = true := by
  decide +kernel
theorem hOG : (List.range 104).all
    (fun v => Glue{k}.zm.testBit v || decide (v ∈ Glue{k}.O) || (typeMask.getD {k} 0).testBit v) = true := by
  decide +kernel
{spec}
/-- **C(P104) ≥ 56 for framed type {k}** (hypotheses of BForm: `Capacity`, `BicliqueFact`, `CensusFact`). -/
theorem floor {{K : Type*}} [Field K] [CharZero K] (hcap : BForm.Capacity BForm.E8.labK)
    (hbic : BForm.BicliqueFact (BForm.E8.rK K)) (hcensus : BForm.CensusFact BForm.E8.labK (BForm.E8.rK K))
    (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, (typeMask.getD {k} 0).testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0)
    (Al Bl : Matrix (Fin 9) (Fin 104) K) (hA : Al * Matrix.of (fun (v : Fin 104) (i : Fin 9) => A v i) = 1)
    (hB : Bl * Matrix.of (fun (v : Fin 104) (i : Fin 9) => B v i) = 1)
    (P' Q' : Matrix (Fin 104) BForm.C9 K) (h : Matrix.of (fun v s : Fin 104 => Mx A B v s) = P' * Q'ᵀ) :
    56 ≤ BForm.cost BForm.E8.labK P' Q' := by
  obtain ⟨hg, hG⟩ := Gram{k}.gramZ A B u hu hZ hdiag hmask (Zero{k}.cov_ne A B u hu hZ hdiag hmask)
  rw [← hzmeq] at hG
  obtain ⟨lam, eta, hrep, -, hin, hcolU, hrowd, hglue, hpinT⟩ := t3_type A B u hu hZ hdiag hmask _ hg hG hfin hfv
    Glue{k}.hz hzm Glue{k}.hOL Glue{k}.hO Glue{k}.hcov hOG Glue{k}.hsm Glue{k}.hsmlt
    (fun v hv d h1 hd => Glue{k}.line hv d h1 hd) (fun h τ L R five => Glue{k}.glue R five) Glue{k}.hSP
{tail} (fun t => by rw [Matrix.of_apply]; exact hdiag t t.2)
    (fun x y hd => by rw [Matrix.of_apply]; exact hmask x x.2 y y.2 (by simp [orth, hd]))
    _ _ Al Bl hA hB (by ext v s; simp [Matrix.mul_apply, Mx, dotProduct]) P' Q' h

end RankNine.Fl{k}
'''
open(f'../lean/RankNine/Cert/Fl{k}.lean', 'w').write(src)
log(f'frame {fi} bytes {len(src)}')
