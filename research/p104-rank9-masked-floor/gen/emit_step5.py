"""Emit ../lean/RankNine/Cert/Step5<k>.lean (bit-packed T1 step-5 certificate, chunked kernel checks) from the JSON
of gen_step5.py.  usage: emit_step5.py k step5.json out.lean"""
import json, sys
k = int(sys.argv[1]); d = json.load(open(sys.argv[2])); out = sys.argv[3]
def pack(vals):
    blocks = []
    for b in range(0, len(vals), 256):
        n = 0
        for i, v in enumerate(vals[b:b + 256]):
            assert 0 <= v < 65536; n |= v << (16 * i)
        blocks.append(n)
    return '[' + ', '.join(hex(x) for x in blocks) + ']'
flat = lambda rows: [x for r in rows for x in r]
nV = len(d['V']); nNQ = len(d['NQ']); nNT = len(d['NT']); nF = len(d['FS'])
L = [f'''import RankNine.Step5
import RankNine.Cert.Signs{k}

/-! Bit-packed T1 step-5 certificate for framed type {k} (generated by gen/emit_step5.py):
{nV} vertices, {nNQ} quadruple rows, {nNT} `N = 1/4` entries, {nF} directed facts. -/

namespace RankNine.Step5c{k}

open Matrix RankNine.Packed{k} RankNine.Signs{k}

def nV : ℕ := {nV}
def nNQ : ℕ := {nNQ}
def nNT : ℕ := {nNT}
def nF : ℕ := {nF}
def V : List ℕ := {pack(d['V'])}
def PL : List ℕ := {pack(d['PL'])}
def II : List ℕ := {pack(d['II'])}
def TN : List ℕ := {pack(d['TN'])}
def NQ : List ℕ := {pack(flat(d['NQ']))}
def NT : List ℕ := {pack(flat(d['NT']))}
def FS : List ℕ := {pack(flat(d['FS']))}
def ST : List ℕ := {pack(flat(d['ST']))}
''']
def chunked(name, pred, n, ch, var):
    cs = [(a, min(ch, n - a)) for a in range(0, n, ch)]
    for i, (a, mm) in enumerate(cs):
        L.append(f"theorem {name}{i} : (List.range' {a} {mm}).all ({pred}) = true := by decide +kernel\n")
    L.append(f'theorem {name}_ok : ∀ {var} < {n}, ({pred}) {var} = true := by\n  intro {var} h{var}')
    for i, (a, mm) in enumerate(cs):
        if i < len(cs) - 1:
            L.append(f"  by_cases h{i} : {var} < {a + mm}\n  · exact (all_range'_iff _ {a} {mm}).1 {name}{i} {var} (by omega) (by omega)")
        else:
            L.append(f"  exact (all_range'_iff _ {a} {mm}).1 {name}{i} {var} (by omega) (by omega)")
    L.append('')
m = f'(typeMask.getD {k} 0)'
chunked('v', 'vertOK nNT V PL II NT TN', nV, 200, 'i')
chunked('t', f'ntEntryOK {m} nQ nK T CR NQ NT nNQ', nNT, 300, 'n')
chunked('s', f'step5OK {m} nV nNT V PL NT FS ST', nF, 300, 'i')
L.append(f'''/-- T1 step 5 for type {k}: a nonzero gauge `g` with `μ x y g x = γ x y g y` on every listed directed pair (both
directions of every covered pair). -/
theorem gram {{K : Type*}} [Field K] [CharZero K] (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, {m}.testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0)
    (hcov : ∀ c, covB Cv c = true → Nc A B c ≠ 0) :
    (∀ x, gOf A B V PL II nV x ≠ 0) ∧ ∀ i < nF, Gf A B (gOf A B V PL II nV) (fct FS i).1 (fct FS i).2 :=
  step5_sound A B u hu _ hZ hdiag hmask nV nNT nF V PL II NT TN FS ST
    (nt_sound A B u hu _ hZ hdiag hmask nQ nK T CR (moduli_geom A B u hu hZ hdiag hmask hcov)
      (mags A B u hu hZ hdiag hmask hcov) NQ NT nNQ nNT (fun n hn => t_ok n hn))
    (fun i hi => v_ok i hi) (fun i hi => s_ok i hi)

end RankNine.Step5c{k}
''')
open(out, 'w').write('\n'.join(L) + '\n'); print('written', out, 'facts', nF)
