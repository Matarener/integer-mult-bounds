"""Emit ../lean/RankNine/Cert/Gram<k>.lean (T3.1: Gram identity on Z x Z) from the JSON of gram_cert.py.
Pair table PI[104 x + y]: 65534 diagonal, 65535 orthogonal, < 50000 step-5 fact index, 50000 + j frame entry j
(19 fields: x y f, 8 codes (x, f_k), 8 codes (f_k, y)).  Replays RankNine.pairOK in Python before writing.
usage: emit_gram.py k gram.json step5.json out.lean"""
import json, sys
sys.path.insert(0, '.')
from p104lib import frames, IDX, ORTH, P, RT
k = int(sys.argv[1]); d = json.load(open(sys.argv[2])); d5 = json.load(open(sys.argv[3])); out = sys.argv[4]
assert not d['bad'], ('uncovered pairs', d['bad'][:5])
FR = [tuple(IDX[q] for q in f) for f in frames()]
def dot(a, b): return sum(x * y for x, y in zip(RT[P[a]], RT[P[b]]))
def pack(vals):
    blocks = []
    for b in range(0, len(vals), 256):
        n = 0
        for i, v in enumerate(vals[b:b + 256]):
            assert 0 <= v < 65536, v; n |= v << (16 * i)
        blocks.append(n)
    return '[' + ', '.join(hex(x) for x in blocks) + ']' if blocks else '[]'
FS = [tuple(f) for f in d5['FS']]; nF = len(FS); fid = {f: i for i, f in enumerate(FS)}
assert nF < 50000
Z = d['Z']; zm = sum(1 << x for x in Z)
def basic(x, y):
    if x == y: return 65534
    if ORTH[x][y]: return 65535
    return fid.get((x, y))
def bok(x, y, c):   # RankNine.bOK
    if c == 65534: return x == y and dot(x, x) == 18
    if c == 65535: return ORTH[x][y]
    return c < nF and FS[c] == (x, y)
PI = [0] * 10816; GE = []
for j, e in enumerate(d['frames']):
    x, y, fi = e[:3]; F = FR[fi]
    assert all(bok(x, F[t], e[3 + t]) and bok(F[t], y, e[11 + t]) for t in range(8))
    assert sum(dot(x, f) * dot(f, y) for f in F) == 18 * dot(x, y)
    GE += e; PI[104 * x + y] = 50000 + j
nG = len(d['frames']); assert 50000 + nG < 65534
for x in Z:
    for y in Z:
        if PI[104 * x + y] == 0:
            c = basic(x, y); assert c is not None and bok(x, y, c); PI[104 * x + y] = c
CH = 1352
L = [f'''import RankNine.Gram
import RankNine.Cert.Step5c{k}

/-! T3.1 Gram certificate for framed type {k} (generated by gen/emit_gram.py): `Z` of size {len(Z)},
{nF} step-5 facts, {nG} frame entries. -/

namespace RankNine.Gram{k}

open Matrix RankNine.Packed{k} RankNine.Signs{k} RankNine.Step5c{k}

def zm : ℕ := {zm}
def nG : ℕ := {nG}
def GE : List ℕ := {pack(GE)}
def PI : List ℕ := {pack(PI)}
''']
pred = f'fun c => pairOK (typeMask.getD {k} 0) zm nF nG FS GE (c / 104) (c % 104) (fld PI c)'
cs = [(a, min(CH, 10816 - a)) for a in range(0, 10816, CH)]
for i, (a, mm) in enumerate(cs):
    L.append(f"theorem p{i} : (List.range' {a} {mm}).all ({pred}) = true := by decide +kernel\n")
L.append(f'theorem p_ok : ∀ c < 10816, ({pred}) c = true := by\n  intro c hc')
for i, (a, mm) in enumerate(cs):
    if i < len(cs) - 1:
        L.append(f"  by_cases h{i} : c < {a + mm}\n  · exact (all_range'_iff _ {a} {mm}).1 p{i} c (by omega) (by omega)")
    else:
        L.append(f"  exact (all_range'_iff _ {a} {mm}).1 p{i} c (by omega) (by omega)")
L.append(f'''
/-- T3.1 for type {k}: with the T1 gauge `g`, `M x y = (M x x / g x) γ x y g y` on all of `Z × Z`. -/
theorem gramZ {{K : Type*}} [Field K] [CharZero K] (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, (typeMask.getD {k} 0).testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0)
    (hcov : ∀ c, covB Cv c = true → Nc A B c ≠ 0) :
    (∀ x, gOf A B V PL II nV x ≠ 0) ∧ ∀ x < 104, ∀ y < 104, zm.testBit x = true → zm.testBit y = true →
      GramP A B (gOf A B V PL II nV) x y := by
  obtain ⟨hg, hGf⟩ := gram A B u hu hZ hdiag hmask hcov
  exact ⟨hg, gram_sound A B u hu _ hZ hdiag hmask zm nF nG FS GE PI _ hg hGf (fun c hc => p_ok c hc)⟩

end RankNine.Gram{k}
''')
open(out, 'w').write('\n'.join(L) + '\n')
print('GRAM OK type %d Z %d facts %d frame entries %d' % (k, len(Z), nF, nG), flush=True)
