"""Emit ../lean/RankNine/OrthTab.lean (orthogonality table of P104 as 104 bit masks)."""
import sys
sys.path.insert(0, '.')
from p104lib import ORTH
rows = [sum(1 << j for j in range(104) if ORTH[i][j]) for i in range(104)]
L = ['import RankNine.Defs', '', '/-! Generated by gen/gen_orth.py: orthogonality table of P104 (row `i` = bit mask of the lines orthogonal to `i`). -/', '', 'namespace RankNine', '',
     'def orthData : List ℕ := [' + ', '.join(hex(r) for r in rows) + ']', '',
     '/-- table lookup for `orth` (fast in the kernel) -/',
     'def orthB (i j : ℕ) : Bool := ((orthData.getD i 0) >>> j) % 2 == 1', '',
     'theorem orthB_table : ((List.range 104).all fun i => (List.range 104).all fun j => orthB i j == orth i j) = true := by',
     '  decide +kernel', '', 'end RankNine', '']
open('../lean/RankNine/OrthTab.lean', 'w').write('\n'.join(L))
