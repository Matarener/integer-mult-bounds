"""Emit ../lean/RankNine/Cert/Signs<k>.lean (bit-packed T1 sign certificate, chunked kernel checks) from the JSON of
gen_signs.py.  The XOR combinations are replayed here exactly as RankNine.Signs.comboOK checks them.
usage: emit_signs.py k signs.json out.lean"""
import json, sys
sys.path.insert(0, '.')
def pack(vals):
    """blocks of 256 16-bit fields -> Lean list literal (as in emit_packed.py)"""
    blocks = []
    for b in range(0, len(vals), 256):
        n = 0
        for i, v in enumerate(vals[b:b + 256]):
            assert 0 <= v < 65536; n |= v << (16 * i)
        blocks.append(n)
    return '[' + ', '.join(hex(x) for x in blocks) + ']'
k = int(sys.argv[1]); d = json.load(open(sys.argv[2])); out = sys.argv[3]
QS = [x for q in d['quads'] for x in q]; RS = [x for r in d['rels'] for x in r]
nq = len(d['quads']); nrows = nq + len(d['rels']); nK = len(d['classes'])
CB = []; CO = []
for c in d['combos']: CO += [len(CB), len(c)]; CB += c
assert nK <= 5000 and nrows < 65536 and len(CB) < 65536
CH = 200; KCH = 50
L = [f'''import RankNine.Signs
import RankNine.Cert.Packed{k}

/-! Bit-packed T1 sign certificate for framed type {k} (generated by gen/emit_signs.py):
{nq} quadruple rows, {nrows - nq} relation rows, {nK} classes, {len(CB)} combination entries. -/

namespace RankNine.Signs{k}

open Matrix RankNine.Packed{k}

def nK : ℕ := {nK}
def nq : ℕ := {nq}
def nrows : ℕ := {nrows}
def CR : List ℕ := {pack(d['classes'])}
def QS : List ℕ := {pack(QS)}
def RS : List ℕ := {pack(RS)}
def CQ : List ℕ := {pack(d['classQuad'])}
def CB : List ℕ := {pack(CB)}
def CO : List ℕ := {pack(CO)}
''']
def chunked(name, pred, n, ch, var):
    cs = [(a, min(ch, n - a)) for a in range(0, n, ch)]
    for i, (a, m) in enumerate(cs):
        L.append(f"theorem {name}{i} : (List.range' {a} {m}).all ({pred}) = true := by decide +kernel\n")
    L.append(f'theorem {name}_ok : ∀ {var} < {n}, ({pred}) {var} = true := by\n  intro {var} h{var}')
    for i, (a, m) in enumerate(cs):
        if i < len(cs) - 1:
            L.append(f"  by_cases h{i} : {var} < {a + m}\n  · exact (all_range'_iff _ {a} {m}).1 {name}{i} {var} (by omega) (by omega)")
        else:
            L.append(f"  exact (all_range'_iff _ {a} {m}).1 {name}{i} {var} (by omega) (by omega)")
    L.append('')
m = f'(typeMask.getD {k} 0)'
chunked('r', f'rowOK {m} nQ nK T CR QS RS nq', nrows, CH, 'j')
chunked('c', 'classOK QS CQ nq', nK, KCH, 'c')
chunked('x', 'comboOK T QS RS nq nrows CB CO', nK, KCH, 'c')
L.append(f'''/-- T1 sign step for type {k}: every quadruple class has magnitude bit 0, i.e. `N = 1/4` on its quadruples
(`RankNine.quad_quarter`). -/
theorem mags {{K : Type*}} [Field K] [CharZero K] (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, {m}.testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0)
    (hcov : ∀ c, covB Cv c = true → Nc A B c ≠ 0) :
    ∀ c < nK, magN (Nc A B (fld CR c)) = 0 :=
  signs_sound A B u hu _ hZ hdiag hmask nQ nK nq nrows T CR QS RS CQ CB CO
    (moduli_geom A B u hu hZ hdiag hmask hcov) (fun j hj => r_ok j hj) (by decide)
    (fun c hc => c_ok c hc) (fun c hc => x_ok c hc)

end RankNine.Signs{k}
''')
open(out, 'w').write('\n'.join(L) + '\n'); print('written', out, 'rows', nrows, 'classes', nK)
