"""Emit RankNine/Cert/Zero<k>.lean (T1 zero step) from the CNF of zero_cnf.py and CaDiCaL's LRAT proof.
Keeps only the clauses and lemmas the proof needs, renumbers them densely (original clauses first), replays the
Lean checker RankNine.Zero.entryOK exactly (bit-mask unit propagation along the hints) and writes packed tables.
usage: emit_zero.py k cnf origin.json proof.lrat[.xz] out.lean"""
import sys, json, lzma
sys.path.insert(0, '.')
from p104lib import frames, IDX, ORTH
FR = [tuple(IDX[q] for q in f) for f in frames()]
k = int(sys.argv[1]); cnfp, jp, pfp, out = sys.argv[2:6]
CH = 150
def pack(vals):
    blocks = []
    for b in range(0, len(vals), 256):
        n = 0
        for i, v in enumerate(vals[b:b + 256]):
            assert 0 <= v < 65536, v; n |= v << (16 * i)
        blocks.append(n)
    return '[' + ', '.join(hex(x) for x in blocks) + ']'
def pcode(a, b): return 104 * min(a, b) + max(a, b)
cls = []
for line in open(cnfp):
    if line.startswith('p'): continue
    a = list(map(int, line.split())); cls.append(a[:-1])
org = json.load(open(jp))['origin']; assert len(org) == len(cls)
ncls = len(cls)
lem = {}
op = lzma.open if pfp.endswith('.xz') else open
with op(pfp, 'rt') as f:
    for line in f:
        a = line.split()
        if len(a) > 1 and a[1] == 'd': continue
        i = int(a[0]); z = a.index('0', 1); lem[i] = ([int(x) for x in a[1:z]], [int(x) for x in a[z + 1:-1]])
emp = [i for i, (l, h) in lem.items() if not l]; assert emp, 'no empty clause'
root = min(emp)
need = set(); st = [root]
while st:
    i = st.pop()
    if i in need: continue
    need.add(i)
    if i > ncls: st.extend(lem[i][1])
ids = sorted(need); idx = {i: j for j, i in enumerate(ids)}
assert all(i <= ncls for i in ids[:sum(1 for i in ids if i <= ncls)])
E = []; Lt = []; Hn = []
def mask(lits):
    P = Q = 0
    for l in lits:
        if l > 0: P |= 1 << (l - 1)
        else: Q |= 1 << (-l - 1)
    return P, Q
CL = []   # clause bit masks as the Lean checker computes them
for i in ids:
    if i <= ncls:
        o = org[i - 1]; c = cls[i - 1]
        if o[0] == 'r':
            _, t, s, fi, a, b = o; F = FR[fi]; ka, kb = F.index(a), F.index(b)
            x, y, u, v = pcode(t, a), pcode(s, a), pcode(t, b), pcode(s, b)
            X, Y, U, V = x + 1, y + 1, u + 1, v + 1
            var = [sorted([-X, U, V]), sorted([-Y, U, V]), sorted([-U, X, Y]), sorted([-V, X, Y])].index(sorted(c))
            E += [0, t, s, fi, ka, kb, var]
        elif o[0] == 'q':
            _, t, fi = o; F = FR[fi]; ks = [F.index(f) for f in F if not ORTH[t][f]]
            assert len(ks) == 4 and sorted(-(pcode(t, F[q]) + 1) for q in ks) == sorted(c)
            E += [1, t, fi] + ks
        else:
            E += [2, 0, 0, 0, 0, 0, 0]
        P, Q = mask(c)
        if o[0] == 'g': P = sum(1 << (l - 1) for l in c); Q = 0
    else:
        l, h = lem[i]
        lo, ho = len(Lt), len(Hn)
        Lt += [2 * (abs(x) - 1) + (1 if x > 0 else 0) for x in l]; Hn += [idx[x] for x in h]
        E += [3, lo, len(l), ho, len(h), 0, 0]
        P, Q = mask(l)
    CL.append((P, Q))
n = len(ids)
# replay entryOK for the lemmas (same arithmetic as RankNine.Zero.unitStep / rupRun)
def log2(x): return x.bit_length() - 1
def unit(T, F, c):
    rp = c[0] ^ (c[0] & F); rq = c[1] ^ (c[1] & T)
    if rp == 0 and rq == 0: return 0, T, F
    if rq == 0 and rp == 1 << log2(rp): return 1, T | rp, F
    if rp == 0 and rq == 1 << log2(rq): return 1, T, F | rq
    return 2, T, F
for j in range(n):
    if E[7 * j] != 3: continue
    ho, hn = E[7 * j + 3], E[7 * j + 4]; hs = Hn[ho:ho + hn]
    assert all(h < j for h in hs)
    T, F = CL[j][1], CL[j][0]; ok = False
    for h in hs:
        r, T, F = unit(T, F, CL[h])
        if r == 0: ok = True; break
        if r == 2: break
    assert ok, ('RUP replay failed', j)
assert CL[n - 1] == (0, 0)
norig = sum(1 for i in ids if i <= ncls)
L = [f'''import RankNine.Zero
import RankNine.Cert.Packed{k}
/-! T1 zero step for framed type {k} (generated by gen/emit_zero.py from a CaDiCaL LRAT proof):
{n} entries ({norig} original clauses, {n - norig} lemmas), {len(Hn)} hints. -/
namespace RankNine.Zero{k}
open Matrix
def n : ℕ := {n}
def E : List ℕ := {pack(E)}
def Lt : List ℕ := {pack(Lt) if Lt else '[]'}
def Hn : List ℕ := {pack(Hn) if Hn else '[]'}
''']
chunks = [(a, min(CH, n - a)) for a in range(0, n, CH)]
for i, (a, m) in enumerate(chunks):
    L.append(f"theorem e{i} : (List.range' {a} {m}).all (entryOK (typeMask.getD {k} 0) Packed{k}.Cv E Lt Hn) = true := by decide +kernel\n")
L.append(f'theorem entries_ok : ∀ j < n, entryOK (typeMask.getD {k} 0) Packed{k}.Cv E Lt Hn j = true := by\n  intro j hj')
for i, (a, m) in enumerate(chunks):
    if i < len(chunks) - 1:
        L.append(f"  by_cases h{i} : j < {a + m}\n  · exact (all_range'_iff _ {a} {m}).1 e{i} j (by omega) (by omega)")
    else:
        L.append(f"  exact (all_range'_iff _ {a} {m}).1 e{i} j (by omega) (by simp only [n] at hj; omega)")
L.append(f'''
theorem last_ok : clAt Packed{k}.Cv E Lt (n - 1) = (0, 0) := by decide +kernel

/-- zero step for type {k}: `N ≠ 0` on the whole cover set of the moduli certificate -/
theorem cov_ne {{K : Type*}} [Field K] (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, (typeMask.getD {k} 0).testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0) :
    ∀ c, covB Packed{k}.Cv c = true → Nc A B c ≠ 0 :=
  zero_sound A B u hu _ hZ hdiag hmask Packed{k}.Cv E Lt Hn n entries_ok last_ok (by decide)

/-- moduli step for type {k} without the cover hypothesis -/
theorem moduli_full {{K : Type*}} [Field K] (A B : ℕ → Fin 9 → K) (u : Fin 9 → K) (hu : u ≠ 0)
    (hZ : ∀ x, (typeMask.getD {k} 0).testBit x = true → A x ⬝ᵥ u = 0)
    (hdiag : ∀ x < 104, A x ⬝ᵥ B x ≠ 0) (hmask : ∀ x < 104, ∀ y < 104, orth x y = true → A x ⬝ᵥ B y = 0) :
    ∀ q < Packed{k}.nQ, Nc A B (fld Packed{k}.T (3 * q)) ^ 2 = Nc A B (fld Packed{k}.T (3 * q + 1)) ^ 2 :=
  Packed{k}.moduli_geom A B u hu hZ hdiag hmask (cov_ne A B u hu hZ hdiag hmask)

end RankNine.Zero{k}
''')
open(out, 'w').write('\n'.join(L) + '\n')
print('ZERO OK type %d entries %d orig %d lemmas %d hints %d lits %d' % (k, n, norig, n - norig, len(Hn), len(Lt)), flush=True)
