"""Generate RankNine/Data.lean: P104 roots (A8 coordinates, exact integers), the 759 frames, 387 framed type masks."""
import json, sys
sys.path.insert(0, '.')
from p104lib import *
out = sys.argv[1]
F = [tuple(IDX[q] for q in f) for f in frames()]
reps = [r for r in json.load(open('orbitsW.json')) if r['frame']]
L = []
L.append('/-! Generated by lean-gen/gen_data.py (Internal rank9-p104-2026-10-29). Do not edit. -/')
L.append('namespace RankNine\n')
L.append('/-- the 104 lines of P104 as 9-bit labels of weight 3 or 7 (A8 coordinates) -/')
L.append('def labelData : List Nat := [' + ', '.join(map(str, P)) + ']\n')
L.append('set_option maxHeartbeats 4000000 in')
L.append('/-- the 759 frames (8 pairwise orthogonal lines) of P104, as sorted index lists -/')
L.append('def frameData : List (List Nat) := [\n  ' + ',\n  '.join('[' + ', '.join(map(str, f)) + ']' for f in F) + ']\n')
L.append('/-- the 387 framed orbit representatives of dead sets C(W), as bit masks over line indices -/')
L.append('def typeMask : List Nat := [\n  ' + ',\n  '.join(str(int(r['mask'])) for r in reps) + ']\n')
L.append('end RankNine')
open(out, 'w').write('\n'.join(L) + '\n')
print('frames', len(F), 'types', len(reps))
