"""Emit RankNine/Cert/Packed<k>.lean (bit-packed moduli certificate, chunked kernel checks) from
lean-gen/cert/moduli-<k>.json.  Facts are replayed here exactly as RankNine.Packed.stepOK checks them."""
import json, sys
k = int(sys.argv[1]); out = sys.argv[2]; CH = int(sys.argv[3]) if len(sys.argv) > 3 else 400
d = json.load(open(sys.argv[4] if len(sys.argv) > 4 else 'cert/moduli-%d.json' % k))
def pack(vals):
    n = 0
    for i, v in enumerate(vals):
        assert 0 <= v < 65536; n |= v << (16 * i)
    return n
def orient(o, r):
    x, p, y, q = r
    return [(x, p, y, q), (p, x, y, q), (x, p, q, y), (p, x, q, y), (y, q, x, p), (q, y, x, p), (y, q, p, x), (q, y, p, x)][o % 8]
rels = [tuple(r) for r in d['rels']]; facts = []
for s in d['steps']:
    t = s[0]
    if t == 0: x, p, y, q = orient(s[3], rels[s[1]]); facts.append((x, y))
    elif t == 1: x, p, y, q = orient(s[2], rels[s[1]]); facts.append((p, q))
    elif t == 2: facts.append((facts[s[1]][0], facts[s[2]][1]))
    else: facts.append((facts[s[1]][1], facts[s[1]][0]))
R = pack([x for r in rels for x in r]); S = pack([x for s in d['steps'] for x in (list(s) + [0] * (5 - len(s)))])
F = pack([x for f in facts for x in f]); Cv = sum(1 << c for c in d['cov'])
Q = pack([x for q, qf in zip(d['quads'], d['quadfacts']) for x in [qf[0]] + [y for c, f in zip(q, qf[1:]) for y in (c, 0 if f == -1 else f + 1)]])
n = len(facts); nR = len(rels); nQ = len(d['quads'])
chunks = [(a, min(CH, n - a)) for a in range(0, n, CH)]
qch = [(a, min(CH, nQ - a)) for a in range(0, nQ, CH)]
L = [f'''import RankNine.Packed

/-! Bit-packed moduli certificate for framed type {k} (generated by lean-gen/emit_packed.py):
{nR} relations, {n} steps/facts, {nQ} quadruples. -/

namespace RankNine.Packed{k}

def nR : ℕ := {nR}
def n : ℕ := {n}
def nQ : ℕ := {nQ}
def R : ℕ := {hex(R)}
def S : ℕ := {hex(S)}
def F : ℕ := {hex(F)}
def Cv : ℕ := {hex(Cv)}
def Q : ℕ := {hex(Q)}
''']
for i, (a, m) in enumerate(chunks):
    L.append(f'theorem s{i} : (List.range\' {a} {m}).all (stepOK nR R S F Cv) = true := by decide +kernel\n')
L.append('theorem steps_ok : ∀ i < n, stepOK nR R S F Cv i = true := by\n  intro i hi')
for i, (a, m) in enumerate(chunks):
    if i < len(chunks) - 1:
        L.append(f'  by_cases h{i} : i < {a + m}\n  · exact (all_range\'_iff _ {a} {m}).1 s{i} i (by omega) (by omega)')
    else:
        L.append(f'  exact (all_range\'_iff _ {a} {m}).1 s{i} i (by omega) (by simp only [n] at hi; omega)')
L.append('')
for i, (a, m) in enumerate(qch):
    L.append(f'theorem q{i} : (List.range\' {a} {m}).all (fun q => (List.range 4).all (qEntryOK n F Q q)) = true := by decide +kernel\n')
L.append('theorem quads_ok : ∀ q < nQ, ∀ j < 4, qEntryOK n F Q q j = true := by\n  intro q hq j hj\n  have key : (List.range 4).all (qEntryOK n F Q q) = true := by')
for i, (a, m) in enumerate(qch):
    if i < len(qch) - 1:
        L.append(f'    by_cases h{i} : q < {a + m}\n    · exact (all_range\'_iff _ {a} {m}).1 q{i} q (by omega) (by omega)')
    else:
        L.append(f'    exact (all_range\'_iff _ {a} {m}).1 q{i} q (by omega) (by simp only [nQ] at hq; omega)')
L.append('''  simp only [List.all_eq_true, List.mem_range] at key
  exact key j hj

/-- T1 moduli step for this type: on every quadruple all four entries have the square of the root entry. -/
theorem moduli {K : Type*} [Field K] (N : ℕ → K) (hrel : ∀ j < nR, holds N (relAt R j))
    (hcov : ∀ c, covB Cv c = true → N c ≠ 0) :
    ∀ q < nQ, ∀ j < 4, N (fld Q (9 * q + 1 + 2 * j)) ^ 2 = N (fld Q (9 * q)) ^ 2 := by
  intro q hq j hj
  exact qEntryOK_sound N n F Q q j (steps_sound N nR R S F Cv n hrel hcov steps_ok) (quads_ok q hq j hj)
''')
L.append(f'end RankNine.Packed{k}')
open(out, 'w').write('\n'.join(L) + '\n'); print('written', out, 'chunks', len(chunks), len(qch), 'size', sum(len(x) for x in L))
