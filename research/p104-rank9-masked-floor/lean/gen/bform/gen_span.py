"""Generate BForm/E8h/SpanData.lean: odd-port masks O(l) for all 512 labels l (in the order of `lists9`), and for
every positive root j the port masks N_j (non-orthogonal), P_j (positive), M_j (negative inner product).
Apache-2.0."""
import itertools, json
from pathlib import Path as _P
GD = _P(__file__).resolve().parent; OUT = str(GD.parent / 'BForm' / 'E8h') + '/'; DATA = str(GD.parent.parent / 'data') + '/'
H = DATA
D = json.load(open(H + 'p104_port_labels.json')); P = D['P']; R = json.load(open(H + 'p104_r8_d8.json'))['R8']
pos = json.load(open(str(GD / "hand_data.json")))['pos']
dot = lambda a, b: sum(x * y for x, y in zip(a, b))
# lists9 = (List.replicate 9 [0,1]).sections: coordinate 0 varies fastest
L9 = [[(i >> k) & 1 for k in range(9)] for i in range(512)]
pbits = lambda t: [(P[t] >> k) & 1 for k in range(9)]
par = lambda t, l: sum(a * b for a, b in zip(pbits(t), l)) % 2 == 1
O = [sum(1 << t for t in range(104) if par(t, l)) for l in L9]
N = [sum(1 << t for t in range(104) if dot(R[t], r) != 0) for r in pos]
Pm = [sum(1 << t for t in range(104) if dot(R[t], r) > 0) for r in pos]
Mm = [sum(1 << t for t in range(104) if dot(R[t], r) < 0) for r in pos]
J = lambda x: json.dumps(x, separators=(',', ':'))
out = ['/-! Generated by gen_span.py: odd-port masks of the 512 labels (order of `lists9`) and the port masks of the',
       'positive roots (non-orthogonal, positive, negative inner product). -/', '', 'namespace BForm.E8h', '',
       'def oData : List (List Nat × Nat) := [' + ',\n  '.join('(%s,%d)' % (J(l), o) for l, o in zip(L9, O)) + ']', '',
       'def oBad : List (List Nat × Nat) := [' + ','.join('(%s,%d)' % (J(l), o) for l, o in zip(L9, O) if l != [0]*9 and bin(o).count('1') < 47) + ']', '',
       'def nMask : List Nat := ' + J(N), '', 'def pMask : List Nat := ' + J(Pm), '', 'def mMask : List Nat := ' + J(Mm), '',
       'end BForm.E8h', '']
open(OUT + 'SpanData.lean', 'w').write('\n'.join(out))
# python-side sanity of the planned checks
pc = lambda s: bin(s).count('1')
zero = [0] * 9
assert min(pc(o) for l, o in zip(L9, O) if l != zero) == 44
bad = [(l, o) for l, o in zip(L9, O) if l != zero and pc(o) < 47]; print('bad z', len(bad))
lab = {tuple(pbits(t)): t for t in range(104)}
for j in range(120):
    for l, o in zip(L9, O):
        if l == zero: continue
        s = o & N[j]
        assert s == 0 or pc(s) >= 5 or (pc(s) == 1 and lab.get(tuple(l)) == s.bit_length() - 1)
cnt = 0
for a in range(120):
    for b in range(120):
        if dot(pos[a], pos[b]) != 0: continue
        for eps in (1, -1):
            same = (Pm[a] & Pm[b]) | (Mm[a] & Mm[b]); opp = (Pm[a] & Mm[b]) | (Mm[a] & Pm[b])
            nv = (N[a] ^ N[b]) | (same if eps == 1 else opp)
            v = [x + eps * y for x, y in zip(pos[a], pos[b])]
            assert nv == sum(1 << t for t in range(104) if dot(R[t], v) != 0)
            for l, o in bad:
                s = o & nv; assert s == 0 or pc(s) >= 5; cnt += 1
print('python checks ok', cnt)
