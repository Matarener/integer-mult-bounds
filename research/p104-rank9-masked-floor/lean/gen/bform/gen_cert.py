"""Generate BForm/E8h/Cert.lean: explicit simple roots and linear-combination certificates for the E7 and D7
parabolic cases.  Apache-2.0."""
import json
from pathlib import Path as _P
GD = _P(__file__).resolve().parent; OUT = str(GD.parent / 'BForm' / 'E8h') + '/'; DATA = str(GD.parent.parent / 'data') + '/'
from fractions import Fraction as Fr
D = json.load(open(str(GD / "hand_data.json"))); pos = D['pos']; ti = D['theta']; a7, b7 = D['d7']
dot = lambda a, b: sum(x * y for x, y in zip(a, b))
def lstsq(cols, target):
    # solve sum_i m_i cols[i] = target exactly (cols independent)
    n = len(cols); G = [[Fr(dot(c, d)) for d in cols] for c in cols]; rhs = [Fr(dot(c, target)) for c in cols]
    A = [G[i] + [rhs[i]] for i in range(n)]
    for c in range(n):
        p = next(r for r in range(c, n) if A[r][c] != 0); A[c], A[p] = A[p], A[c]
        A[c] = [x / A[c][c] for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0: A[r] = [x - A[r][c] * y for x, y in zip(A[r], A[c])]
    m = [A[i][n] for i in range(n)]
    assert all(sum(m[i] * cols[i][k] for i in range(n)) == target[k] for k in range(8)), 'not in span'
    return m
def fr(x): return '(%s)' % (str(x.numerator) if x.denominator == 1 else '%d/%d' % (x.numerator, x.denominator))
def cert(simples, normal, nn, name, hyp_doc):
    lines = []
    for c in range(8):
        e = [Fr(int(k == c)) for k in range(8)]
        tgt = [e[k] - Fr(normal[c] * normal[k], nn) for k in range(8)]
        m = lstsq([pos[i] for i in simples], tgt)
        lines.append(' + '.join('%s * h%d' % (fr(m[q]), simples[q]) for q in range(len(simples)) if m[q] != 0) or '0')
    return lines
out = ['import Mathlib', 'import BForm.E8h.Data', '', 'set_option linter.unusedSimpArgs false', '', '/-! Generated by gen_cert.py: the simple roots, θ and ω₁ explicitly, and',
       'linear-combination certificates: a vector orthogonal to `α₁ … α₇` is a multiple of `θ`, one orthogonal to',
       '`α₂ … α₈` is a multiple of `ω₁ = r_a + r_b`. -/', '', 'namespace BForm.E8h', '', 'open Matrix', '']
V = lambda v: '![' + ', '.join(str(x) for x in v) + ']'
for i in list(range(8)) + [a7, b7]:
    out.append('theorem pos_%d : posData.getD %d [] = [%s] := rfl' % (i, i, ', '.join(str(x) for x in pos[i])))
out.append('')
def block(name, simples, normal, nn, normal_expr):
    L = cert(simples, normal, nn, name, '')
    s = ['theorem %s {K : Type*} [Field K] [CharZero K] (y : Fin 8 → K)' % name]
    for i in simples:
        s.append('    (h%d : (%s : Fin 8 → K) ⬝ᵥ y = 0)' % (i, V(pos[i])))
    s.append('    : y = (((%s : Fin 8 → K) ⬝ᵥ y) / %d) • (%s : Fin 8 → K) := by' % (V(normal), nn, V(normal)))
    s.append('  simp only [dotProduct, Fin.sum_univ_eight, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.cons_val] at *')
    s.append('  funext k')
    s.append('  fin_cases k <;> simp only [Pi.smul_apply, smul_eq_mul, dotProduct, Fin.sum_univ_eight, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.cons_val, Fin.zero_eta, Fin.mk_one, Fin.reduceFinMk]')
    for c in range(8):
        s.append('  · linear_combination %s' % L[c])
    return s
w1 = [x + y for x, y in zip(pos[a7], pos[b7])]
out += block('e7_cert', list(range(7)), pos[ti], dot(pos[ti], pos[ti]), None) + ['']
out += block('d7_cert', list(range(1, 8)), w1, dot(w1, w1), None) + ['']
out += ['end BForm.E8h', '']
open(OUT + 'Cert.lean', 'w').write('\n'.join(out))
print('\n'.join(out[-40:]))
