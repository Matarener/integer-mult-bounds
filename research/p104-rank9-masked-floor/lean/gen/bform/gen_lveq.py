"""Generate BForm/E8h/LvEq.lean: explicit coordinates of the simple roots, theta and the D7 pair.  Apache-2.0."""
import json
from pathlib import Path as _P
GD = _P(__file__).resolve().parent; OUT = str(GD.parent / 'BForm' / 'E8h') + '/'; DATA = str(GD.parent.parent / 'data') + '/'
D = json.load(open(str(GD / "hand_data.json"))); pos = D['pos']
out = ['import BForm.E8h.Refl', '', '/-! Generated by gen_lveq.py: explicit coordinates of the simple roots, θ and the D7 pair. -/', '',
       'namespace BForm.E8h', '', 'open Matrix', '']
for i in list(range(8)) + D['d7']:
    out.append('theorem lv_eq_%d {K : Type*} [Field K] : lv K %d = (![%s] : Fin 8 → K) := by' % (i, i, ', '.join(str(x) for x in pos[i])))
    out.append('  funext k; fin_cases k <;> simp only [lv, pr, pos_%d] <;> simp' % i)
out += ['', 'end BForm.E8h', '']
open(OUT + 'LvEq.lean', 'w').write('\n'.join(out))
