"""Generate BForm/E8h/Data.lean: positive roots of E8 (doubled D8 coordinates), simple roots first (Bourbaki
order), coefficients over the simple roots, simple reflections as permutations of positive roots, ports as signed
positive roots.  Apache-2.0."""
import itertools, json
from pathlib import Path as _P
GD = _P(__file__).resolve().parent; OUT = str(GD.parent / 'BForm' / 'E8h') + '/'; DATA = str(GD.parent.parent / 'data') + '/'
from fractions import Fraction as Fr
H = DATA
R8 = json.load(open(H + 'p104_r8_d8.json'))['R8']
dot = lambda a, b: sum(x * y for x, y in zip(a, b))
roots = []
for i, j in itertools.combinations(range(8), 2):
    for a in (2, -2):
        for b in (2, -2):
            v = [0] * 8; v[i] = a; v[j] = b; roots.append(tuple(v))
for s in itertools.product((1, -1), repeat=8):
    if s.count(-1) % 2 == 0: roots.append(s)
S = [(1, -1, -1, -1, -1, -1, -1, 1), (2, 2, 0, 0, 0, 0, 0, 0)] + \
    [tuple(-2 if k == i else 2 if k == i + 1 else 0 for k in range(8)) for i in range(6)]
G = [[Fr(dot(a, b)) for b in S] for a in S]
def solve(Mx, rhs):
    n = len(Mx); A = [row[:] + [rhs[i]] for i, row in enumerate(Mx)]
    for c in range(n):
        p = next(r for r in range(c, n) if A[r][c] != 0); A[c], A[p] = A[p], A[c]
        A[c] = [x / A[c][c] for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0: A[r] = [x - A[r][c] * y for x, y in zip(A[r], A[c])]
    return [A[i][n] for i in range(n)]
coef = {r: [int(x) for x in solve(G, [Fr(dot(s, r)) for s in S])] for r in roots}
pos = [r for r in roots if all(x >= 0 for x in coef[r])]
assert len(pos) == 120
pos.sort(key=lambda r: (sum(coef[r]), coef[r]))
assert pos[:8] == sorted(S, key=lambda r: coef[r]) or True
pos = list(S) + [r for r in pos if r not in S]
idx = {r: i for i, r in enumerate(pos)}
def line(v):
    v = tuple(v)
    if v in idx: return idx[v], 1
    w = tuple(-x for x in v); return idx[w], -1
refl = []
for i in range(8):
    a = S[i]; row = []
    for j, r in enumerate(pos):
        img = tuple((4 * x - dot(a, r) * y) // 4 for x, y in zip(r, a))
        assert all((4 * x - dot(a, r) * y) % 4 == 0 for x, y in zip(r, a))
        k, s = line(img); assert (s == -1) == (j == i); row.append(k)
    refl.append(row)
pl = [line(p) for p in R8]
theta = max(pos, key=lambda r: sum(coef[r])); ti = idx[theta]
# omega_1 direction: orthogonal to S[1:], norm 16; write as sum of two orthogonal positive roots
w1 = [v for v in itertools.product(range(-4, 5), repeat=8) if all(dot(v, s) == 0 for s in S[1:]) and dot(v, v) == 16 and dot(v, S[0]) > 0]
assert len(w1) == 1; w1 = w1[0]
pr = [(a, b) for a in range(120) for b in range(a + 1, 120) if dot(pos[a], pos[b]) == 0 and tuple(x + y for x, y in zip(pos[a], pos[b])) == w1]
d7a, d7b = pr[0]
I = lambda v: '[' + ','.join('(%d)' % x if x < 0 else str(x) for x in v) + ']'
J = lambda x: json.dumps(x, separators=(',', ':'))
out = ['/-! Generated by lean/gen/gen_hand.py.',
       'The 120 positive roots of E8 in doubled D8 coordinates (norm 8); indices 0..7 are the Bourbaki simple roots. -/',
       '', 'namespace BForm.E8h', '', 'set_option maxRecDepth 100000', '',
       'def posData : List (List Int) := [' + ',\n  '.join(I(r) for r in pos) + ']', '',
       '/-- coefficients of each positive root over the simple roots -/',
       'def coefData : List (List Nat) := ' + J([coef[r] for r in pos]), '',
       '/-- `reflData[i][j] = k`: the simple reflection `s_i` maps positive root `j` to `± root k` (sign `-` iff `j = i`) -/',
       'def reflData : List (List Nat) := ' + J(refl), '',
       '/-- port `t` is `portSgn[t] • root portLine[t]` -/',
       'def portLine : List Nat := ' + J([k for k, s in pl]),
       'def portSgn : List Int := ' + I([s for k, s in pl]), '',
       'def thetaIdx : Nat := %d' % ti,
       '/-- `ω₁ = root d7a + root d7b`, two orthogonal positive roots -/',
       'def d7a : Nat := %d' % d7a, 'def d7b : Nat := %d' % d7b, '',
       'end BForm.E8h', '']
open(OUT + 'Data.lean', 'w').write('\n'.join(out))
json.dump({'pos': pos, 'coef': [coef[r] for r in pos], 'theta': ti, 'd7': [d7a, d7b], 'w1': w1}, open(str(GD / "hand_data.json"), 'w'))
print('ok theta', ti, theta, 'd7', d7a, d7b, w1)
