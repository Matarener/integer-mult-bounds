"""Exact frame-meet minima on the 120 E8 root lines and the uniform F' ceiling.

Standard library only. See README.md for the statement and proof.
"""
import itertools
import json
import pathlib
import sys
from fractions import Fraction

FRAME_SIZE = 8


def require(cond, msg):
    """Contract check that stays active under python -O."""
    if not cond:
        raise SystemExit("FAIL: " + msg)


def e8_lines():
    """The 120 lines of E8 as doubled integer coordinates (norm 8)."""
    roots = []
    for i, j in itertools.combinations(range(8), 2):
        for si in (2, -2):
            for sj in (2, -2):
                v = [0] * 8
                v[i], v[j] = si, sj
                roots.append(tuple(v))
    for signs in itertools.product((1, -1), repeat=8):
        if signs.count(-1) % 2 == 0:
            roots.append(signs)
    require(len(roots) == 240, 'len(roots) == 240')
    lines = sorted(r for r in roots if next(x for x in r if x) > 0)
    require(len(lines) == 120, 'len(lines) == 120')
    return lines


def dot(u, v):
    return sum(a * b for a, b in zip(u, v))


def canonical_line(v):
    return v if next(x for x in v if x) > 0 else tuple(-x for x in v)


def build():
    lines = e8_lines()
    n = len(lines)
    pos = {v: i for i, v in enumerate(lines)}
    gram = [[dot(a, b) // 4 for b in lines] for a in lines]
    require(all(gram[i][i] == 2 for i in range(n)), 'all(gram[i][i] == 2 for i in range(n))')
    require(all(abs(gram[i][j]) in (0, 1) for i in range(n) for j in range(n) if i != j), 'all(abs(gram[i][j]) in (0, 1) for i in range(n) for j in ran')
    orth = [sum(1 << j for j in range(n) if j != i and gram[i][j] == 0) for i in range(n)]
    return lines, pos, gram, orth


def maximal_orthogonal_sets(n, orth):
    """All maximal cliques of the orthogonality graph (bounded DFS, depth <= 8)."""
    out = []
    stack = [(1 << i, orth[i] & ~((1 << (i + 1)) - 1), orth[i]) for i in range(n)]
    while stack:
        members, cand, common = stack.pop()
        require(bin(members).count("1") <= FRAME_SIZE, 'bin(members).count("1") <= FRAME_SIZE')
        if common == 0:
            out.append(members)
        c = cand
        while c:
            t = (c & -c).bit_length() - 1
            c &= c - 1
            stack.append((members | 1 << t, cand & orth[t] & ~((1 << (t + 1)) - 1), common & orth[t]))
    return sorted(out)


def reflections(lines, pos):
    """Permutation of the 120 lines induced by the reflection in each root."""
    perms = []
    for r in lines:
        perm = []
        for v in lines:
            c = dot(v, r) // 4  # <v,r> in root normalisation (roots of norm 2)
            w = tuple(a - c * b for a, b in zip(v, r))
            perm.append(pos[canonical_line(w)])
        require(sorted(perm) == list(range(len(lines))), 'sorted(perm) == list(range(len(lines)))')
        perms.append(perm)
    return perms


def popcount(x):
    return bin(x).count("1")


def meet_bitsets(n, frames):
    fb = [0] * n
    for j, members in enumerate(frames):
        for t in range(n):
            if members >> t & 1:
                fb[t] |= 1 << j
    return fb


def orthogonal_sets(n, orth, s):
    """Sorted tuples of s pairwise-orthogonal lines (bounded DFS, depth s)."""
    out = []
    stack = [((i,), orth[i] & ~((1 << (i + 1)) - 1)) for i in range(n)]
    while stack:
        members, cand = stack.pop()
        if len(members) == s:
            out.append(members)
            continue
        c = cand
        while c:
            t = (c & -c).bit_length() - 1
            c &= c - 1
            stack.append((members + (t,), cand & orth[t] & ~((1 << (t + 1)) - 1)))
    return out


def orbit_representatives(sets, perms):
    """Least element of each orbit of `sets` under the group generated by `perms`."""
    index = {x: i for i, x in enumerate(sets)}
    seen = [False] * len(sets)
    reps = []
    for i, start in enumerate(sets):
        if seen[i]:
            continue
        seen[i] = True
        reps.append(start)
        queue = [start]
        while queue:  # each set enters the queue at most once
            cur = queue.pop()
            for p in perms:
                img = tuple(sorted(p[t] for t in cur))
                j = index[img]  # KeyError would mean a non-automorphism
                if not seen[j]:
                    seen[j] = True
                    queue.append(img)
    return reps


def caro_wei_floor(k, edges):
    """Least integer >= k^2/(k+2*edges): every graph on k vertices with
    `edges` edges has an independent set this large (Caro-Wei/Turan)."""
    return -((-k * k) // (k + 2 * edges))


def extension_minimum(n, orth, fb, rep, k, pmax):
    """Minimum meet over k-sets D containing `rep` with at most pmax non-orthogonal pairs."""
    base = 0
    for t in rep:
        base |= fb[t]
    rep_mask = sum(1 << t for t in rep)
    nonorth = [((1 << n) - 1) & ~orth[t] & ~(1 << t) for t in range(n)]
    best, minimisers = None, []
    stack = [(rep_mask, base, 0, ((1 << n) - 1) & ~rep_mask, len(rep))]
    while stack:  # depth <= k - len(rep)
        members, union, pairs, cand, size = stack.pop()
        if size == k:
            v = popcount(union)
            if best is None or v < best:
                best, minimisers = v, []
            if v == best:
                minimisers.append(members)
            continue
        c = cand
        while c:
            t = (c & -c).bit_length() - 1
            c &= c - 1
            q = pairs + popcount(nonorth[t] & members)
            if q <= pmax:
                stack.append((members | 1 << t, union | fb[t], q, c, size + 1))
    return best, minimisers


def exact_minimum(n, orth, fb, frames, perms, k, per, pair_max):
    """Exact least meet over all k-sets of lines, via Bonferroni + Caro-Wei + orbits."""
    frame0 = [t for t in range(n) if frames[0] >> t & 1]
    seed = 0
    for t in frame0[:k]:
        seed |= fb[t]
    incumbent = popcount(seed)
    # Bonferroni: meet(D) >= per*k - pair_max*(orthogonal pairs of D).
    pmax = (incumbent - per * k + pair_max * (k * (k - 1) // 2)) // pair_max
    s = caro_wei_floor(k, pmax)
    require(1 <= s <= k, '1 <= s <= k')
    reps = orbit_representatives(orthogonal_sets(n, orth, s), perms)
    best, minimisers = incumbent, []
    for rep in reps:
        value, found = extension_minimum(n, orth, fb, rep, k, pmax)
        require(value is not None, "representative has no extension")
        if value < best:
            best, minimisers = value, []
        if value == best:
            minimisers.extend(found)
    require(best <= incumbent, 'best <= incumbent')
    nonorth_pairs = sorted({sum(1 for a, b in itertools.combinations(
        [t for t in range(n) if d >> t & 1], 2) if not orth[a] >> b & 1) for d in minimisers})
    return {"k": k, "seed_frame_subset": incumbent, "pair_cap": pmax,
            "orthogonal_core": s, "core_orbits": len(reps), "minimum": best,
            "minimiser_nonorthogonal_pairs": nonorth_pairs}


def check_automorphisms(perms, frames):
    """Each reflection permutes the maximal orthogonal sets, so it preserves meet."""
    frame_set = set(frames)
    for p in perms:
        for f in frames:
            img = sum(1 << p[t] for t in range(len(p)) if f >> t & 1)
            require(img in frame_set, "reflection does not permute the frames")


def unit_analysis(n, orth, perms, frame_count, frame_size, per, pair_max, sizes):
    frames = maximal_orthogonal_sets(n, orth)
    require(len(frames) == frame_count, "maximal orthogonal set count")
    require({popcount(f) for f in frames} == {frame_size}, "maximal orthogonal set size")
    fb = meet_bitsets(n, frames)
    pairs = [(a, b) for a in range(n) for b in range(a + 1, n)]
    require({popcount(x) for x in fb} == {per}, "sets through each line")
    require({popcount(fb[a] & fb[b]) for a, b in pairs if orth[a] >> b & 1} == {pair_max},
            "sets through each orthogonal pair")
    require({popcount(fb[a] & fb[b]) for a, b in pairs if not orth[a] >> b & 1} == {0},
            "sets through a non-orthogonal pair")
    check_automorphisms(perms, frames)
    return frames, fb, {k: exact_minimum(n, orth, fb, frames, perms, k, per, pair_max) for k in sizes}


def e7_control(lines, gram, all_perms):
    """Positive control: E7 = lines orthogonal to line 0 (predecessor MILP 55, 62, 68)."""
    unit = [t for t in range(len(lines)) if gram[t][0] == 0]
    loc = {t: i for i, t in enumerate(unit)}
    orth = [sum(1 << loc[s] for s in unit if s != t and gram[t][s] == 0) for t in unit]
    perms = [[loc[all_perms[r][t]] for t in unit] for r in unit]
    _, _, exact = unit_analysis(len(unit), orth, perms, 135, 7, 15, 3, (5, 6, 7))
    return {str(k): {"minimum": v["minimum"], "frame_subset": v["seed_frame_subset"],
                     "minimiser_nonorthogonal_pairs": v["minimiser_nonorthogonal_pairs"]}
            for k, v in exact.items()}


def main():
    lines, pos, gram, orth = build()
    n = len(lines)
    perms = reflections(lines, pos)
    per, pair_max = 135, 15
    frames, fb, exact = unit_analysis(n, orth, perms, 2025, FRAME_SIZE, per, pair_max, (7, 8))
    bonferroni = {k: per * k - pair_max * (k * (k - 1) // 2) for k in range(1, 7)}
    ratio = {k: Fraction(k, bonferroni[k]) for k in bonferroni}
    ratio.update({k: Fraction(k, exact[k]["minimum"]) for k in exact})
    y = max(ratio.values())
    require(y == ratio[8] and all(ratio[k] < y for k in ratio if k != 8), "size 8 binds")
    ceiling = len(frames) * y
    require(ceiling == Fraction(360, 17), "uniform F' ceiling equals Theorem C value")
    # Rejecting control: any smaller uniform weight violates a frame's constraint.
    frame_meet = popcount(sum_bits(fb, frames[0], n))
    require(Fraction(8, 766) * frame_meet < 8 and y * frame_meet == 8, "frame constraint is tight")
    control = e7_control(lines, gram, perms)
    require(control["7"]["minimum"] == 68 and control["7"]["frame_subset"] == 71,
            "E7 control reproduces the predecessor MILP value 68 below the frame value 71")
    return {
        "unit": "P120 (all 120 E8 root lines)",
        "maximal_orthogonal_sets": len(frames),
        "sets_through_line": per, "sets_through_orthogonal_pair": pair_max,
        "sets_through_nonorthogonal_pair": 0,
        "exact_minimum_meet": {str(k): exact[k] for k in exact},
        "bonferroni_floor_k_le_6": {str(k): v for k, v in bonferroni.items()},
        "binding_size": 8,
        "uniform_weight": str(y),
        "uniform_fprime_ceiling": str(ceiling),
        "previous_proven_fprime_ceiling": "24",
        "theorem_c_f_ceiling": "360/17",
        "e7_positive_control": control,
    }


def sum_bits(fb, members, n):
    out = 0
    for t in range(n):
        if members >> t & 1:
            out |= fb[t]
    return out


