"""synth.backgen -- BACK-END plan generators for the FRONTGEN word (GENBACK, see ../module docstring).  Scope [toolkit synth, back-end sign-network generator].

plan(method, ctx) -> dict(copies=[dict(k, cin)], ysteps={j:[(frame_id,[(copy_index, coef),...],[res_carrier_index,...]), ...]}, rcar=None|[dict(i)], info=...)
 * rcar=None means the star residual (one private carrier per nonzero residual (j,i), read at Q_j); otherwise a RESIDUAL CARRIER is a helper holding x_i (born 0, += X_i at L_i) read by the listed Ys at the listed frames.
 * a COPY is a helper (born at frame 0, ends at F9) that receives `cin * root_k` at the root's landing line <l_k> (equal-frame ADD from the owned root), then climbs through the frames at which Y's read it.
 * a Y STEP is (frame, reads): Y_j is brought to the frame (one MOVE, lazy hops) and does Y_j += coef * copy for every read, the copy being at the SAME frame.
   Steps of one Y must be a chain of nested frames ending inside Q_j = p_j^perp (the final Y frame); the residual carriers are read afterwards at Q_j by frontgen.
 * the event order is generated by frontgen: steps whose frame is not Q_j are emitted sorted by frame dimension (nested chains => every register's frames ascend), then the Q_j steps.
Methods ('back: generated:<method>' in the spec / `tk synth --front-gen --back <method>`):
  star      one private copy per (j,k) (cin = 2*C_jk), Y reads all of them at Q_j.  The FRONTGEN back end (reference).
  gray      Hasse/Gray prefix sharing: roots in index order, Y_j climbs the chain V_{k1} < V_{k1k2} < ... (V_B = span of the lines l_k, k in B, dim |B|) adding the copy of root k_t at V_{B_t};
            the copies of one root are the min chain cover (Dilworth, bipartite matching) of the distinct pairs (k, B).  cin = 1, Y coefficient 2*C_jk.
  dilworth  same engine, but each Y's root ORDER and GROUPING of roots into stops is optimised (simulated annealing on the exact entropy-tax model, data/backgen_dilworth.json) so that the chain cover (the 'width') and the Y fragmentation tax are jointly small.
"""
import os,sys,json,math,random,collections
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,os.path.dirname(HERE))
from fractions import Fraction as Q
DATA=os.path.join(HERE,'data','backgen_dilworth.json')
METHODS=('star','gray','dilworth','grouped')
def _H(r): return r*math.log(r)
def tax(ranks,tot):
    """first-order fragmentation tax (units of kappa*1) of splitting one rank-`tot` climb into the given rank pieces: sum r ln r deficit (weights r^(1-kappa))"""
    return tot*math.log(tot)-sum(_H(r) for r in ranks if r>0)
def chain_cover(sets,lt=None):
    """minimum chain cover (Dilworth, bipartite matching) of distinct items under a strict partial order (default: proper inclusion of frozensets) -> list of chains (ascending)"""
    lt=lt or (lambda a,b:a<b)
    n=len(sets); adj=[[b for b in range(n) if lt(sets[a],sets[b])] for a in range(n)]; mt=[-1]*n
    def tr(a,seen):
        for b in adj[a]:
            if b in seen: continue
            seen.add(b)
            if mt[b]<0 or tr(mt[b],seen): mt[b]=a; return True
        return False
    for a in range(n): tr(a,set())
    nxt={mt[b]:b for b in range(n) if mt[b]>=0}; hasprev={b for b in range(n) if mt[b]>=0}; chains=[]
    for a in range(n):
        if a in hasprev: continue
        c=[a]
        while c[-1] in nxt: c.append(nxt[c[-1]])
        chains.append([sets[x] for x in c])
    return chains
def cost_model(steps_of):
    """steps_of[j] = list of tuples of roots (one tuple per Y stop, ascending nested sets B_t = union of the first t tuples).  -> (copies, ytax, ctax, pairs->chains)"""
    pairs=collections.defaultdict(set); ytax=0.0
    for steps in steps_of:
        B=set(); dims=[]
        for g in steps:
            B|=set(g)
            for k in g: pairs[k].add(frozenset(B))
            dims.append(len(B))
        ranks=[dims[0]]+[dims[i]-dims[i-1] for i in range(1,len(dims))]+[8-dims[-1]]
        ytax+=tax(ranks,8)
    ncopy=0; ctax=0.0; cov={}
    for k,ss in pairs.items():
        ss=sorted(ss,key=lambda s:(len(s),sorted(s))); cov[k]=chain_cover(ss)
        for ch in cov[k]:
            dd=sorted({1}|{len(s) for s in ch}); ranks=[dd[0]]+[dd[i]-dd[i-1] for i in range(1,len(dd))]+[9-dd[-1]]
            ctax+=tax(ranks,9); ncopy+=1
    return ncopy,ytax,ctax,cov
def patterns(C2): return [tuple(k for k in range(len(C2[0])) if C2[j][k]) for j in range(len(C2))]
def gray_steps(C2): return [[(k,) for k in p] for p in patterns(C2)]
def optimise_steps(C2,iters=30000,seed=5):
    """simulated annealing over per-Y (root order, grouping into stops); objective = Y fragmentation tax + copy tax (entropy model, 1 unit = kappa*5.96e-8-ish).  Deterministic."""
    pats=patterns(C2); rng=random.Random(seed)
    def rnd(p):
        p=list(p); rng.shuffle(p); st=[]; i=0
        while i<len(p):
            n=1 if rng.random()<.7 else rng.randint(1,3); st.append(tuple(p[i:i+n])); i+=n
        return st
    cur=gray_steps(C2); n,y,c,_=cost_model(cur); cs=y+c; best=(cs,[list(x) for x in cur])
    for it in range(iters):
        j=rng.randrange(len(pats)); old=cur[j]; cur[j]=rnd(pats[j]) if rng.random()<.5 else [tuple(sorted(g)) for g in old]
        if cur[j]==old: continue
        n,y,c,_=cost_model(cur); s=y+c; T=2.0*(1-it/iters)+.01
        if s<=cs or rng.random()<math.exp((cs-s)/T):
            cs=s
            if cs<best[0]: best=(cs,[list(x) for x in cur])
        else: cur[j]=old
    return best
def load_dilworth_steps(C2):
    import hashlib
    sha=hashlib.sha256(json.dumps(C2).encode()).hexdigest()[:16]
    if os.path.exists(DATA):
        J=json.load(open(DATA))
        if J.get('c2_sha')==sha: return [[tuple(g) for g in st] for st in J['steps']]
    s,steps=optimise_steps(C2); J=dict(c2_sha=sha,objective=s,steps=[[list(g) for g in st] for st in steps])
    try: json.dump(J,open(DATA,'w'))
    except OSError: pass
    return [[tuple(g) for g in st] for st in steps]
def plan(method,ctx):
    C2=ctx['C2']; m=len(C2); K=len(C2[0]); fid=ctx['fid']; line=ctx['line']; Qf=ctx['Qf']
    if method=='star':
        copies=[]; ys={}
        for j in range(m):
            rd=[]
            for k in range(K):
                if C2[j][k]: copies.append(dict(k=k,cin=Q(2*C2[j][k]))); rd.append((len(copies)-1,Q(1)))
            ys[j]=[(Qf[j],rd,[])]
        return dict(copies=copies,ysteps=ys,rcar=None,info=dict(method=method,copies=len(copies)))
    if method=='grouped': return plan_grouped(ctx)
    if method not in METHODS: raise ValueError('unknown back method %r (have %s)'%(method,METHODS))
    steps_of=gray_steps(C2) if method=='gray' else load_dilworth_steps(C2)
    n,yt,ct,cov=cost_model(steps_of)
    copies=[]; cidx={}
    for k in range(K):
        for ch in cov.get(k,[]):
            copies.append(dict(k=k,cin=Q(1)))
            for B in ch: cidx[(k,B)]=len(copies)-1
    ys={}
    for j,steps in enumerate(steps_of):
        B=set(); out=[]
        for g in steps:
            B|=set(g); fr=fid([line[k] for k in sorted(B)])
            out.append((fr,[(cidx[(k,frozenset(B))],Q(2*C2[j][k])) for k in g],[]))
        ys[j]=out
    return dict(copies=copies,ysteps=ys,rcar=None,info=dict(method=method,copies=len(copies),model_ytax=yt,model_ctax=ct,y_stops=sum(len(s) for s in steps_of)))
# ------------------------------------------------------------------ grouped: laminar tree of Y groups (shared residual carriers + shared signal copies)
GDATA=os.path.join(HERE,'data','backgen_groups.json')
_par=lambda a,b:bin(a&b).count('1')&1
def _pmask(p): return sum(1<<x for x in range(512) if not _par(x,p))                # vectors orthogonal to p (the frame Q = p^perp)
def _mpop(a): return bin(a).count('1')
def _mdim(a): return _mpop(a).bit_length()-1
def _mbasis(mask):
    b=[]; sp={0}
    for x in range(1,512):
        if (mask>>x)&1 and x not in sp: b.append(x); sp|={y^x for y in sp}
    return b
def build_tree(P):
    """agglomerative merging of the Y's: merge the two clusters whose union has the most ports in the common frame V_G = (span p_j, j in G)^perp (maximal shared residual carriers).  Returns (merges, masks)"""
    m=len(P); pm=sum(1<<p for p in P); mask={j:_pmask(P[j]) for j in range(m)}; grp={j:frozenset([j]) for j in range(m)}; live=set(range(m)); merges=[]; nid=m
    while len(live)>1:
        best=None; L=sorted(live)
        for ai in range(len(L)):
            for bi in range(ai+1,len(L)):
                a,b=L[ai],L[bi]; fm=mask[a]&mask[b]; key=(_mpop(fm&pm),-len(grp[a])-len(grp[b]))
                if best is None or key>best[0]: best=(key,a,b,fm)
        _,a,b,fm=best; mask[nid]=fm; grp[nid]=grp[a]|grp[b]; merges.append((a,b)); live-={a,b}; live.add(nid); nid+=1
    return merges,mask
def _tree_cost(P,line,C2,merges,mask,sel,detail=False):
    m=len(P); K=len(C2[0]); parent={}
    for n,(a,b) in enumerate(merges,m): parent[a]=n; parent[b]=n
    chains={}
    for j in range(m):
        c=[j]
        while c[-1] in parent: c.append(parent[c[-1]])
        c=[n for n in c if n==j or n in sel]; seen=set(); out=[]
        for n in sorted(c,key=lambda n:(_mpop(mask[n]),n!=j)):         # smallest frame (largest group) first; equal frames: keep the first
            if mask[n] in seen: continue
            seen.add(mask[n]); out.append(n)
        chains[j]=out
    ytax=0.0
    for j in range(m):
        ds=sorted({_mdim(mask[n]) for n in chains[j]}); ytax+=tax([ds[0]]+[ds[i]-ds[i-1] for i in range(1,len(ds))],8)
    use=collections.defaultdict(lambda:collections.defaultdict(list)); cuse=collections.defaultdict(lambda:collections.defaultdict(list))
    for j in range(m):
        for i in range(m):
            if _par(P[i],P[j]): continue
            for n in chains[j]:
                if (mask[n]>>P[i])&1: use[i][mask[n]].append(j); break
        for k in range(K):
            if C2[j][k]:
                for n in chains[j]:
                    if (mask[n]>>line[k])&1: cuse[k][mask[n]].append(j); break
    sub=lambda a,b:a!=b and (a&~b)==0
    def cover(d,first,tot):
        t=0.0; chs=[]
        if not d: return t,chs
        for ch in chain_cover(sorted(d,key=_mpop),sub):
            ds=sorted({first}|{_mdim(f) for f in ch}); t+=tax([ds[0]]+[ds[i]-ds[i-1] for i in range(1,len(ds))],tot); chs.append(ch)
        return t,chs
    rt=0.0; rch={}; st=0.0; sch={}
    for i,d in use.items(): t,chs=cover(d,1,9); rt+=t; rch[i]=chs
    for k,d in cuse.items(): t,chs=cover(d,1,9); st+=t; sch[k]=chs
    tot=ytax+rt+st
    if detail: return tot,dict(ytax=ytax,rtax=rt,stax=st,chains=chains,use=use,cuse=cuse,rch=rch,sch=sch,nres=sum(len(c) for c in rch.values()),ncopy=sum(len(c) for c in sch.values()))
    return tot
def grouped_structure(P,line,C2):
    import hashlib
    sha=hashlib.sha256(json.dumps([P,line,C2]).encode()).hexdigest()[:16]
    if os.path.exists(GDATA):
        J=json.load(open(GDATA))
        if J.get('sha')==sha: return [tuple(x) for x in J['merges']],set(J['sel'])
    merges,mask=build_tree(P); m=len(P); mask=dict(mask)
    sel={n for n in range(m,m+len(merges)) if sum(1 for p in P if (mask[n]>>p)&1)>0}; cur=_tree_cost(P,line,C2,merges,mask,sel); imp=True
    while imp:
        imp=False
        for n in sorted(sel):
            sel.discard(n); c=_tree_cost(P,line,C2,merges,mask,sel)
            if c<cur-1e-9: cur=c; imp=True
            else: sel.add(n)
    try: json.dump(dict(sha=sha,objective=cur,merges=[list(x) for x in merges],sel=sorted(sel)),open(GDATA,'w'))
    except OSError: pass
    return merges,sel
def plan_grouped(ctx):
    C2=ctx['C2']; P=ctx['ports']; line=ctx['line']; fid=ctx['fid']; Qf=ctx['Qf']; m=len(P); K=len(C2[0])
    merges,sel=grouped_structure(P,line,C2); mask={j:_pmask(P[j]) for j in range(m)}
    for n,(a,b) in enumerate(merges,m): mask[n]=mask[a]&mask[b]
    tot,D=_tree_cost(P,line,C2,merges,mask,sel,detail=True)
    fidm={}
    def F(mk):
        if mk not in fidm: fidm[mk]=fid(_mbasis(mk))
        return fidm[mk]
    copies=[]; rcar=[]; steps=collections.defaultdict(lambda:collections.defaultdict(lambda:dict(c=[],r=[])))
    for k,chs in D['sch'].items():
        for ch in chs:
            copies.append(dict(k=k,cin=Q(1))); ci=len(copies)-1
            for mk in ch:
                for j in D['cuse'][k][mk]: steps[j][F(mk)]['c'].append((ci,Q(2*C2[j][k])))
    for i,chs in D['rch'].items():
        for ch in chs:
            rcar.append(dict(i=i)); ri=len(rcar)-1
            for mk in ch:
                for j in D['use'][i][mk]: steps[j][F(mk)]['r'].append(ri)
    ys={}
    for j in range(m):
        assert F(mask[j])==Qf[j]
        ys[j]=[(f,v['c'],v['r']) for f,v in steps[j].items()]
    return dict(copies=copies,ysteps=ys,rcar=rcar,info=dict(method='grouped',copies=len(copies),rcarriers=len(rcar),model_total=tot,model_ytax=D['ytax'],model_rtax=D['rtax'],model_stax=D['stax'],y_stops=sum(len(v) for v in ys.values())))
