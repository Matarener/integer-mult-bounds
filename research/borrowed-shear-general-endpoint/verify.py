#!/usr/bin/env python3
"""Exact borrowed-space shear minima for general endpoints diag(T, I_q).

Alphabet (PR #5640): gathers G(A): z <- z + A x and scatters S(B): x <- x + B z,
with x in K^n (data) and z in K^q (arbitrary dirty borrowed coordinates).
A word implements diag(T, I_q) when it maps (x0, z0) to (T x0, z0) for all inputs.

For each small domain this script runs a breadth-first search over the whole
group generated by the alphabet, so each recorded distance is the exact minimum
number of shears. It then checks every reachable endpoint against

    tariff(T) = 2 ceil(r/q) + 2                 if (T - I)^2 = 0,
    tariff(T) = max(2 ceil(r/q) + 2, 6)          otherwise,   r = rank(T - I) > 0,

replays one shortest witness word per endpoint on the full (n+q)-square matrix,
and runs rejecting controls.
"""
import hashlib
import itertools
import json
import pathlib
import sys

# (p, n, q): every domain is enumerated completely.
DOMAINS = ((2, 2, 1), (2, 2, 2), (2, 3, 1), (3, 2, 1), (5, 2, 1))
MAX_GROUP = 400_000


def check(condition, message):
    """Explicit check that stays active under python -O."""
    if not condition:
        raise SystemExit("FAIL: " + message)


def generators(p, n, q):
    """Each generator is (kind, target_column, ((source_column, coeff), ...)) lists.

    Right multiplication by G(A) adds sum_a A[a][j] * column(n+a) to column j;
    right multiplication by S(B) adds sum_i B[i][a] * column(i) to column n+a.
    """
    gens = []
    for vals in itertools.product(range(p), repeat=q * n):
        if not any(vals):
            continue
        gather = tuple((j, tuple((n + a, vals[a * n + j]) for a in range(q) if vals[a * n + j]))
                       for j in range(n))
        scatter = tuple((n + a, tuple((i, vals[a * n + i]) for i in range(n) if vals[a * n + i]))
                        for a in range(q))
        gens.append(("G", vals, gather))
        gens.append(("S", vals, scatter))
    return gens


def apply_gen(p, m, X, gen):
    """Return X * g for a row-major flat matrix X (tuple of length m*m)."""
    cols = [X[c::m] for c in range(m)]
    new = list(cols)
    for target, sources in gen[2]:
        if not sources:
            continue
        col = list(cols[target])
        for src, coeff in sources:
            col = [(a + coeff * b) % p for a, b in zip(col, cols[src])]
        new[target] = col
    return tuple(new[c][r] for r in range(m) for c in range(m))


def gen_matrix(p, n, q, gen):
    """Literal (n+q)-square matrix of a generator, built from its definition."""
    m = n + q
    M = [[int(i == j) for j in range(m)] for i in range(m)]
    kind, vals = gen[0], gen[1]
    for a in range(q):
        for b in range(n):
            if kind == "G":
                M[n + a][b] = vals[a * n + b]  # z_a += A[a][b] x_b
            else:
                M[b][n + a] = vals[a * n + b]  # x_b += B[b][a] z_a
    return M


def matmul(p, X, Y):
    return [[sum(X[i][k] * Y[k][j] for k in range(len(Y))) % p for j in range(len(Y[0]))]
            for i in range(len(X))]


def rank(p, M):
    rows = [list(r) for r in M]
    r = 0
    for c in range(len(rows[0]) if rows else 0):
        piv = next((i for i in range(r, len(rows)) if rows[i][c] % p), None)
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        inv = pow(rows[r][c], p - 2, p)
        rows[r] = [v * inv % p for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] % p:
                f = rows[i][c]
                rows[i] = [(a - f * b) % p for a, b in zip(rows[i], rows[r])]
        r += 1
    return r


def bfs(p, n, q):
    m = n + q
    gens = generators(p, n, q)
    ident = tuple(int(i == j) for i in range(m) for j in range(m))
    parent = {ident: None}
    dist = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for X in frontier:
            for gi, g in enumerate(gens):
                Y = apply_gen(p, m, X, g)
                if Y not in dist:
                    dist[Y] = dist[X] + 1
                    parent[Y] = (X, gi)
                    nxt.append(Y)
        check(len(dist) <= MAX_GROUP, "group exceeds bounded size")
        frontier = nxt
    return gens, dist, parent


def word_to(parent, X):
    word = []
    while parent[X] is not None:
        X, gi = parent[X]
        word.append(gi)
    return word[::-1]


def tariff(r, q, square_zero):
    base = 2 * (-(-r // q)) + 2
    return base if square_zero else max(base, 6)


def census(p, n, q):
    m = n + q
    gens, dist, parent = bfs(p, n, q)
    rows = {}
    old_formula_misses = 0
    for X, d in dist.items():
        full = [list(X[i * m:(i + 1) * m]) for i in range(m)]
        if any(full[n + a][j] != int(n + a == j) for a in range(q) for j in range(m)):
            continue
        if any(full[i][n + a] for i in range(n) for a in range(q)):
            continue
        T = [row[:n] for row in full[:n]]
        N = [[(T[i][j] - int(i == j)) % p for j in range(n)] for i in range(n)]
        r = rank(p, N)
        if r == 0:
            check(d == 0, "identity must cost zero")
            continue
        sq0 = not any(v for row in matmul(p, N, N) for v in row)
        want = tariff(r, q, sq0)
        check(d == want, f"F{p} n={n} q={q}: T={T} minimum {d} != tariff {want}")
        if d != 2 * (-(-r // q)) + 2:
            old_formula_misses += 1
        # Replay one shortest witness on the literal full matrix.
        word = word_to(parent, X)
        check(len(word) == d, "witness length differs from distance")
        prod = [[int(i == j) for j in range(m)] for i in range(m)]
        for gi in word:
            prod = matmul(p, prod, gen_matrix(p, n, q, gens[gi]))
        check(prod == full, "witness word does not replay to diag(T, I)")
        kinds = [gens[gi][0] for gi in word]
        check(all(a != b for a, b in zip(kinds, kinds[1:])), "shortest word must alternate")
        if not sq0:
            check(kinds.count("G") >= 3 and kinds.count("S") >= 3,
                  "non-square-zero witness with at most two gathers or scatters")
        key = f"r={r},square_zero={sq0},min={d}"
        rows[key] = rows.get(key, 0) + 1
    return {"p": p, "n": n, "q": q, "group_order": len(dist),
            "endpoint_classes": dict(sorted(rows.items())),
            "endpoints_checked": sum(rows.values()) + 1,
            "pr5640_formula_underestimates": old_formula_misses}


def controls():
    """Rejecting controls: a wrong tariff and a corrupted witness must fail."""
    out = {}
    # Control 1: the square-zero-only tariff 2ceil(r/q)+2 is refuted on F2, n=q=2.
    res = census(2, 2, 2)
    check(res["pr5640_formula_underestimates"] == 2, "expected two non-square-zero misses")
    out["square_zero_formula_refuted_on_F2_n2_q2"] = res["pr5640_formula_underestimates"]
    # Control 2: a single corrupted coefficient in a witness changes the endpoint.
    p, n, q = 3, 2, 1
    gens, dist, parent = bfs(p, n, q)
    m = n + q
    target = next(X for X, d in dist.items() if d == 6
                  and all(X[(n + a) * m + j] == int(n + a == j) for a in range(q) for j in range(m))
                  and all(X[i * m + n + a] == 0 for i in range(n) for a in range(q)))
    word = word_to(parent, target)
    bad = list(word)
    g0 = gens[bad[0]]
    alt = next(i for i, g in enumerate(gens) if g[0] == g0[0] and g[1] != g0[1])
    bad[0] = alt
    prod = [[int(i == j) for j in range(m)] for i in range(m)]
    for gi in bad:
        prod = matmul(p, prod, gen_matrix(p, n, q, gens[gi]))
    full = [list(target[i * m:(i + 1) * m]) for i in range(m)]
    check(prod != full, "corrupted witness unexpectedly replays")
    out["corrupted_witness_rejected"] = True
    return out


def main():
    results = [census(*dom) for dom in DOMAINS]
    totals = {"non_square_zero_endpoints": 0, "square_zero_endpoints": 0}
    for res in results:
        for key, count in res["endpoint_classes"].items():
            totals["square_zero_endpoints" if "square_zero=True" in key
                   else "non_square_zero_endpoints"] += count
    payload = {"domains": results, "totals": totals, "controls": controls()}
    here = pathlib.Path(__file__).resolve().parent
    digest = hashlib.sha256()
    for name in sorted(f.name for f in here.iterdir() if f.is_file()):
        digest.update(name.encode() + b"\0" + (here / name).read_bytes())
    payload["package_sha256"] = digest.hexdigest()
    print(json.dumps(payload, indent=1, sort_keys=True))
    print("PASS_BORROWED_SHEAR_GENERAL_ENDPOINT")


if __name__ == "__main__":
    sys.exit(main())
