#!/usr/bin/env python3
"""Exact check of the 141 clique certificate for the strict 56-plane port decoder.

The certificate is a feasible point of PR5560's clique programme.  This script checks, from the
pinned selected archive and the PR1825 matching:

1. the 56 matched planes, each nondegenerate, and their 109 orthogonal pairs;
2. the closure census: 39,087 subspaces of F2^9 generated by nonempty plane sets;
3. the tariff t(A, R) = dim A - dim(A meet R^perp) for every ordered pair, cross-checked
   against Gaussian elimination of the pairing matrix on 4,000 random pairs;
4. every certificate column is a clique of pairwise non-orthogonal planes with a positive
   integer weight;
5. feasibility on ALL 39,087^2 ordered pairs (A, R):
       sum_{Q : some plane of Q lies in A and some plane of Q lies in R} w_Q  <=  SCALE * t(A, R);
   slack 0 occurs exactly on the tariff-0 pairs;
6. the bound sum_Q 2|Q| w_Q / SCALE = 36732955/262144 > 140, hence every decoder costs >= 141;
7. rejecting controls: an overweight column, a non-clique column, a wrong recorded bound and
   PR5560's own certificate (which is feasible but does not reach 140) must each fail.

All load sums are integers below 2^40 and all census counts are at most 512, so the float64
and float32 matrix products used here are exact; both facts are asserted.  Needs numpy >= 2.
"""
import hashlib, json, random, sys, tarfile, time
from fractions import Fraction
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ARCHIVE = ROOT / 'research/community-frontier1094-audit/selected-replay.tar.gz'
ARCHIVE_SHA = 'f1da80610bf33c58527f18ad63b4350d0b864e1d4486141ee17ac9bed4d529d6'
MEMBER = 'candidate/strict/global/base/work/complex-nine-native/DATA-PHASES.json'
MATCHING = ROOT / 'research/paired-plane-port-matching-seed6c563a/CERTIFICATE.json'
MATCHING_SHA = '4fd648f7b5178bff5441bf364d58234b7bc1a43b924bc6da03013c948f1473b1'
PRED = ROOT / 'research/plane-port-global-rank-dual/CERTIFICATE.json'
PRED_SHA = '20ccaf90c909c602bacc101f3dc540848c844903506e8bce70eb06f28c1ec342'
N_SPANS = 39087
BLOCK = 2048
T0 = time.time()


class Fail(Exception):
    pass


def need(cond, msg):
    if not cond:
        raise Fail(msg)


def log(*a):
    print('%6.1fs' % (time.time() - T0), *a, flush=True)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def parity(x):
    return bin(x).count('1') & 1


def f2_rank(rows):
    rank = 0
    rows = [r for r in rows if r]
    while rows:
        p = rows.pop()
        low = p & -p
        rows = [r ^ p if r & low else r for r in rows]
        rows = [r for r in rows if r]
        rank += 1
    return rank


def planes():
    need(sha(ARCHIVE) == ARCHIVE_SHA, 'archive hash')
    need(sha(MATCHING) == MATCHING_SHA, 'matching hash')
    with tarfile.open(ARCHIVE) as a:
        labels = [r['q'] for r in json.loads(a.extractfile(a.getmember(MEMBER)).read())['recipes']]
    match = json.loads(MATCHING.read_text())['matching']
    need(len(labels) == 112 and len(match) == 56, 'port and plane counts')
    need(sorted(p for e in match for p in e) == list(range(112)), 'perfect matching')
    pl = [(labels[a], labels[b]) for a, b in match]
    for x, y in pl:
        need(f2_rank([x, y]) == 2, 'plane is two-dimensional')
        need(parity(x & x) * parity(y & y) ^ parity(x & y) == 1, 'plane Gram is nonsingular over F2')
    orth = np.array([[i != j and all(parity(u & v) == 0 for u in pl[i] for v in pl[j]) for j in range(56)]
                     for i in range(56)])
    need(int(orth.sum()) == 2 * 109, '109 orthogonal plane pairs')
    return pl, orth


def census(pl):
    """subspaces generated by nonempty plane sets, as sorted tuples of basis-reduced generators"""
    def reduce(basis, v):
        for b in basis:
            v = min(v, v ^ b)
        return v

    def canon(vectors):
        basis = []
        for v in vectors:
            v = reduce(basis, v)
            if v:
                basis = [min(b, b ^ v) for b in basis] + [v]
        # fully reduced echelon form is unique for a subspace
        basis.sort(reverse=True)
        out = []
        for v in basis:
            v = reduce(out, v)
            out = [min(b, b ^ v) for b in out] + [v]
        return tuple(sorted(out))

    seen = set(); frontier = set()
    for x, y in pl:
        frontier.add(canon([x, y]))
    seen |= frontier
    while frontier:
        new = set()
        for s in frontier:
            for x, y in pl:
                t = canon(list(s) + [x, y])
                if t not in seen:
                    seen.add(t); new.add(t)
        frontier = new
    return sorted(seen, key=lambda b: (len(b), b))


def elements(basis):
    els = [0]
    for b in basis:
        els += [e ^ b for e in els]
    return els


def main():
    full = '--sampled' not in sys.argv
    pl, orth = planes()
    log('56 nondegenerate planes, 109 orthogonal pairs')
    bases = census(pl)
    n = len(bases)
    need(n == N_SPANS, 'census size %d' % n)
    dim = np.array([len(b) for b in bases], dtype=np.int64)
    log('generated subspaces', n, 'by dimension', dict(zip(*map(lambda a: a.tolist(), np.unique(dim, return_counts=True)))))

    S = np.zeros((n, 512), np.float32)
    for k, b in enumerate(bases):
        S[k, elements(b)] = 1
    pmask = np.zeros((56, 512), np.float32)
    for i, (x, y) in enumerate(pl):
        pmask[i, [0, x, y, x ^ y]] = 1
    inside = (S @ pmask.T) == 4                                   # plane i lies in span k
    need(all(inside[k].any() for k in range(n)), 'every span contains a plane')
    D = np.array([[parity(u & v) for v in range(512)] for u in range(512)], dtype=np.float32)
    perpT = ((S @ D) == 0).astype(np.float32).T.copy()            # 512 x n: element in R^perp

    def tariffs(r0, r1):
        cnt = S[r0:r1] @ perpT                                    # |A meet R^perp| <= 512, exact
        c = cnt.astype(np.int64)
        need(bool(((c & (c - 1)) == 0).all()) and int(c.min()) >= 1, 'intersections are subspaces')
        return dim[r0:r1, None] - np.log2(c).round().astype(np.int64)

    rng = random.Random(141)
    for _ in range(40):
        a = rng.randrange(n); row = tariffs(a, a + 1)[0]
        for _ in range(100):
            r = rng.randrange(n)
            gram = [sum(parity(u & v) << j for j, v in enumerate(bases[r])) for u in bases[a]]
            need(int(row[r]) == f2_rank(gram), 'tariff vs Gaussian elimination')
    log('tariff formula matches Gaussian elimination on 4000 random pairs')

    def check(cert, rows):
        scale = cert['scale']; cols = cert['columns']
        need(isinstance(scale, int) and scale > 0, 'scale')
        q = np.zeros((len(cols), 56), np.float64)
        for k, c in enumerate(cols):
            Q = c['clique']
            need(len(set(Q)) == len(Q) > 0 and all(isinstance(i, int) and 0 <= i < 56 for i in Q), 'clique indices')
            need(not any(orth[i][j] for i in Q for j in Q), 'column is a clique of non-orthogonal planes')
            need(isinstance(c['w'], int) and c['w'] > 0, 'positive integer weight')
            q[k, Q] = 1
        w = np.array([c['w'] for c in cols], dtype=np.float64)
        need(float(w.sum()) < 2 ** 40, 'exact float64 range')
        touch = ((inside.astype(np.float64) @ q.T) > 0).astype(np.float64)
        TW = (touch * w).T.copy()
        worst = None; tight = 0; zero = 0
        for r0 in range(0, len(rows), BLOCK):
            rs = rows[r0:r0 + BLOCK]
            lo, hi = rs[0], rs[-1] + 1
            if hi - lo == len(rs):
                t = tariffs(lo, hi)
            else:
                t = np.concatenate([tariffs(a, a + 1) for a in rs])
            load = np.rint(touch[rs] @ TW).astype(np.int64)
            slack = t * scale - load
            m = int(slack.min()); worst = m if worst is None else min(worst, m)
            tight += int((slack == 0).sum()); zero += int((t == 0).sum())
            need(m >= 0, 'feasibility violated in rows %d..%d' % (lo, hi))
        LB = Fraction(sum(2 * len(c['clique']) * c['w'] for c in cols), scale)
        need(LB == Fraction(cert['lower_bound_num'], cert['lower_bound_den']), 'recorded bound')
        return LB, worst, tight, zero

    rows = list(range(n)) if full else list(range(0, n, 97))
    cert = json.loads((HERE / 'CERTIFICATE.json').read_text())
    LB, worst, tight, zero = check(cert, rows)
    need(LB > 140, 'bound exceeds 140')
    need(tight == zero, 'slack 0 occurs only on tariff-0 pairs')
    log('certificate PASSED on', len(rows), 'x', n, 'ordered pairs; min slack', worst, 'tight pairs', tight, '= tariff-0 pairs')

    ctrl = list(range(0, n, 977))
    bad = json.loads(json.dumps(cert)); bad['columns'][-1]['w'] += 10 * cert['scale']
    bad['lower_bound_num'], bad['lower_bound_den'] = Fraction(
        sum(2 * len(c['clique']) * c['w'] for c in bad['columns']), bad['scale']).as_integer_ratio()
    nonclique = json.loads(json.dumps(cert))
    i, j = map(int, np.argwhere(orth)[0]); nonclique['columns'][0]['clique'] = [i, j]
    wrong = json.loads(json.dumps(cert)); wrong['lower_bound_num'] += 1
    for name, c in [('overweight column', bad), ('orthogonal pair as clique', nonclique),
                    ('wrong recorded bound', wrong)]:
        try:
            check(c, ctrl)
        except Fail:
            log('control rejected:', name)
        else:
            raise SystemExit('FAILED: control accepted: ' + name)
    need(sha(PRED) == PRED_SHA, 'PR5560 certificate hash')
    pred = json.loads(PRED.read_text())
    pLB = check(pred, ctrl)[0]
    need(pLB < 140 < LB, 'PR5560 certificate stays below 140; this one exceeds it')
    log('control: PR5560 certificate is feasible on the control rows with bound', float(pLB), '< 140')

    res = {'schema': 'plane-port-clique-floor-141/verify/1', 'planes': 56, 'orthogonal_pairs': 109,
           'generated_subspaces': n, 'ordered_pairs_checked': len(rows) * n, 'complete': full,
           'columns': len(cert['columns']), 'max_clique': max(len(c['clique']) for c in cert['columns']),
           'scale': cert['scale'], 'min_slack': worst, 'tight_pairs': tight, 'tariff_zero_pairs': zero,
           'lower_bound': str(LB), 'lower_bound_float': float(LB), 'integer_floor': 141,
           'new_kappa_claimed': False}
    print(json.dumps(res, indent=1))
    print('PASS_PLANE_PORT_CLIQUE_FLOOR_141' + ('' if full else '_SAMPLED'))


if __name__ == '__main__':
    try:
        main()
    except Fail as e:
        raise SystemExit('FAILED: %s' % e)
