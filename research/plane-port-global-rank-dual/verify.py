#!/usr/bin/env python3
"""Exact replay of the global rank-dual certificate for the 56-plane port decoder.

Checks, from the pinned selected archive and the retained PR1825 matching:

1. the 56 matched planes and their pairwise orthogonality;
2. every subspace of F2^9 generated by a nonempty set of planes (closure census);
3. the binary pairing tariff t(A, R) = dim A - dim(A meet R^perp) for ordered pairs of such
   subspaces, cross-checked against direct Gaussian elimination on 20,000 random pairs;
4. that every certificate column is a clique of pairwise non-orthogonal planes with a positive
   integer weight;
5. feasibility: for every ordered pair (A, R) of generated subspaces,
       sum_{Q : A meets Q and R meets Q} w_Q  <=  SCALE * t(A, R),
   where "A meets Q" means some plane of Q lies inside A;
6. the bound sum_Q w_Q * 2|Q| / SCALE = 18233853/131072;
7. rejecting controls: a perturbed certificate, a non-clique column and a wrong recorded bound
   must each fail.

Step 5 sums are integers below 2^30, so the float64 matrix product used for them is exact
(asserted).  Needs numpy >= 2 (np.bitwise_count).

Default (bounded, for CI): steps 1-4, 6, 7 in full and step 5 on every 97th row (403 rows x all
39,087 columns).  `--full`: step 5 on all 39,087^2 ordered pairs (about 7 minutes on 4 cores);
the receipt is written to FULL-CHECK.json.  `--rows a:b`: step 5 on rows a..b-1.
"""
import argparse, hashlib, json, random, tarfile, time
from fractions import Fraction
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ARCHIVE = ROOT / 'research/community-frontier1094-audit/selected-replay.tar.gz'
ARCHIVE_SHA = 'f1da80610bf33c58527f18ad63b4350d0b864e1d4486141ee17ac9bed4d529d6'
MEMBER = 'candidate/strict/global/base/work/complex-nine-native/DATA-PHASES.json'
MATCHING = ROOT / 'research/paired-plane-port-matching-seed6c563a/CERTIFICATE.json'
MATCHING_SHA = '4fd648f7b5178bff5441bf364d58234b7bc1a43b924bc6da03013c948f1473b1'
T0 = time.time()


def log(*a):
    print('%6.0fs' % (time.time() - T0), *a, flush=True)


class Fail(Exception):
    pass


def need(c, msg):
    if not c:
        raise Fail(msg)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def dot(x, y):
    return bin(x & y).count('1') & 1


def gauss_rank(rows):
    """rank over F2 of a list of int bit-rows"""
    rows = [r for r in rows if r]; rank = 0
    while rows:
        piv = max(rows); top = piv.bit_length() - 1; rank += 1
        rows = [r ^ piv if r >> top & 1 else r for r in rows if r != piv]
        rows = [r for r in rows if r]
    return rank


def basis_of(elems):
    b = []
    for x in elems:
        for y in b:
            x = min(x, x ^ y)
        if x:
            b.append(x)
    return b


def geometry():
    need(sha(ARCHIVE) == ARCHIVE_SHA, 'archive hash')
    need(sha(MATCHING) == MATCHING_SHA, 'matching hash')
    with tarfile.open(ARCHIVE) as a:
        labels = [r['q'] for r in json.loads(a.extractfile(a.getmember(MEMBER)).read())['recipes']]
    matching = json.loads(MATCHING.read_text())['matching']
    need(len(labels) == 112 and len(matching) == 56, 'sizes')
    need(sorted(p for e in matching for p in e) == list(range(112)), 'matching is perfect')
    planes = [(labels[a], labels[b]) for a, b in matching]
    pel = [{0, x, y, x ^ y} for x, y in planes]
    need(all(len(e) == 4 for e in pel), 'planes are 2-dimensional')
    need(all(gauss_rank([sum(dot(x, y) << k for k, y in enumerate(p)) for x in p]) == 2 for p in planes),
         'every plane is nondegenerate')
    orth = [[i != j and all(dot(x, y) == 0 for x in pel[i] for y in pel[j]) for j in range(56)] for i in range(56)]
    return planes, pel, orth


def census(planes):
    """all subspaces generated by nonempty plane sets, as 512-entry element indicators"""
    idx = np.arange(512)
    frontier = {}
    for x, y in planes:
        m = np.zeros(512, bool); m[[0, x, y, x ^ y]] = True; frontier[m.tobytes()] = m
    seen = dict(frontier)
    while frontier:
        F = np.array(list(frontier.values())); new = {}
        for x, y in planes:
            G = F | F[:, idx ^ x] | F[:, idx ^ y] | F[:, idx ^ x ^ y]
            for g in G:
                k = g.tobytes()
                if k not in seen:
                    seen[k] = g; new[k] = g
        frontier = new
    return np.array(sorted(seen.values(), key=lambda m: (m.sum(), m.tobytes())))


def check_certificate(cert, orth, inside, tariff_rows, n, rows, block):
    SCALE = cert['scale']; cols = cert['columns']
    need(isinstance(SCALE, int) and SCALE > 0, 'scale')
    for c in cols:
        Q = c['clique']
        need(len(set(Q)) == len(Q) and all(0 <= i < 56 for i in Q), 'clique indices')
        need(all(not orth[i][j] for i in Q for j in Q if i != j), 'column is a clique of non-orthogonal planes')
        need(isinstance(c['w'], int) and c['w'] > 0, 'positive integer weight')
    w = np.array([c['w'] for c in cols], dtype=np.int64)
    need(int(w.sum()) < 2 ** 50, 'exact float64 range')
    qm = np.zeros((len(cols), 56), bool)
    for k, c in enumerate(cols):
        qm[k, c['clique']] = True
    touch = (inside.astype(np.int32) @ qm.T.astype(np.int32)) > 0          # span a meets clique k
    Tf = touch.astype(np.float64); TW = (Tf * w.astype(np.float64)).T.copy()
    worst = None; tight = 0
    for b0 in range(0, len(rows), block):
        rs = np.array(rows[b0:b0 + block])
        slack = tariff_rows(rs) * SCALE - np.rint(Tf[rs] @ TW).astype(np.int64)
        m = int(slack.min()); worst = m if worst is None else min(worst, m); tight += int((slack == 0).sum())
        need(m >= 0, 'feasibility violated near row %d' % int(rs[0]))
        if b0 // block % 50 == 0 and len(rows) > 1000:
            log('rows', b0 + len(rs), '/', len(rows), 'min slack', worst)
    LB = Fraction(sum(c['w'] * 2 * len(c['clique']) for c in cols), SCALE)
    need(LB == Fraction(cert['lower_bound_num'], cert['lower_bound_den']), 'recorded bound')
    return LB, worst, tight, int(qm.sum(1).max())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rows', default=None)
    ap.add_argument('--full', action='store_true')
    ap.add_argument('--block', type=int, default=64)
    args = ap.parse_args()

    planes, pel, orth = geometry()
    log('56 nondegenerate planes; orthogonal plane pairs', sum(map(sum, orth)) // 2)
    S = census(planes); n = len(S); size = S.sum(1)
    need(all(int(s) & (int(s) - 1) == 0 for s in size), 'closures are subspaces')
    dim = np.log2(size).round().astype(np.int64)
    log('generated subspaces', n, 'by dimension', {int(k): int(v) for k, v in zip(*np.unique(dim, return_counts=True))})
    need(n == 39087, 'census size')
    pmask = np.zeros((56, 512), bool)
    for i, e in enumerate(pel):
        pmask[i, list(e)] = True
    inside = (S.astype(np.int32) @ pmask.T.astype(np.int32)) == 4           # plane i lies inside span a

    Dm = np.array([[dot(x, y) for y in range(512)] for x in range(512)], dtype=np.float32)
    perp = (S.astype(np.float32) @ Dm) == 0
    Sp = np.packbits(S, axis=1, bitorder='little').view(np.uint64)
    Pp = np.packbits(perp, axis=1, bitorder='little').view(np.uint64)

    def tariff_rows(rs):
        cnt = np.bitwise_count(Sp[rs][:, None, :] & Pp[None, :, :]).sum(axis=2, dtype=np.int64)
        return dim[rs, None] - np.log2(cnt).round().astype(np.int64)

    rng = random.Random(2026)
    bases = [basis_of(np.flatnonzero(s).tolist()) for s in S]
    need(all(len(b) == d for b, d in zip(bases, dim)), 'basis sizes')
    checked = 0
    for a in rng.sample(range(n), 200):
        row = tariff_rows(np.array([a]))[0]
        for r in rng.sample(range(n), 100):
            direct = gauss_rank([sum(dot(x, y) << k for k, y in enumerate(bases[r])) for x in bases[a]])
            need(int(row[r]) == direct, 'tariff formula vs Gaussian elimination')
            checked += 1
    log('tariff formula matches Gaussian elimination on', checked, 'random pairs')

    if args.full:
        rows = list(range(n))
    elif args.rows:
        lo, hi = map(int, args.rows.split(':')); rows = list(range(lo, hi))
    else:
        rows = list(range(0, n, 97))
    cert = json.loads((HERE / 'CERTIFICATE.json').read_text())
    LB, worst, tight, maxq = check_certificate(cert, orth, inside, tariff_rows, n, rows, args.block)
    log('certificate PASSED on', len(rows), 'rows x', n, 'columns | min slack', worst, '| tight pairs', tight)

    # rejecting controls (on a small row set containing a tight pair)
    ctrl_rows = rows[:64]
    bad = json.loads(json.dumps(cert))
    bad['columns'][0]['w'] += cert['scale'] * 9                      # cannot fit under any tariff <= 9
    bad['lower_bound_num'], bad['lower_bound_den'] = (Fraction(sum(c['w'] * 2 * len(c['clique']) for c in bad['columns']),
                                                               bad['scale'])).as_integer_ratio()
    nonclique = json.loads(json.dumps(cert))
    i, j = next((i, j) for i in range(56) for j in range(56) if orth[i][j])
    nonclique['columns'][0]['clique'] = [i, j]
    wrong = json.loads(json.dumps(cert)); wrong['lower_bound_num'] += 1
    for name, c in [('overweight column', bad), ('orthogonal pair as clique', nonclique), ('wrong recorded bound', wrong)]:
        try:
            check_certificate(c, orth, inside, tariff_rows, n, ctrl_rows, args.block)
        except Fail:
            log('control rejected:', name)
        else:
            raise SystemExit('FAILED: control accepted: ' + name)

    full = len(rows) == n
    res = {'schema': 'plane-port-global-rank-dual/verify/1', 'planes': 56, 'generated_subspaces': n,
           'ordered_pairs_checked': len(rows) * n, 'complete': full, 'columns': len(cert['columns']),
           'max_clique': maxq, 'scale': cert['scale'], 'min_slack': worst, 'tight_pairs': tight,
           'lower_bound': str(LB), 'lower_bound_float': float(LB), 'new_kappa_claimed': False}
    print(json.dumps(res, indent=1))
    if full:
        (HERE / 'FULL-CHECK.json').write_text(json.dumps(res, indent=1) + '\n')
    print('PASS_PLANE_PORT_GLOBAL_RANK_DUAL' + ('_FULL' if full else '_SAMPLED'))


if __name__ == '__main__':
    try:
        main()
    except Fail as e:
        raise SystemExit('FAILED: %s' % e)
