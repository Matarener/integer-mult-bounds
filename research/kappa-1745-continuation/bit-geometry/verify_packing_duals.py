#!/usr/bin/env python3
"""Verify saved complex controller-packing duals without NumPy or SciPy.

The pattern catalogue here is independently generated by a bounded Cartesian
product, rather than the solver script's capacity recursion. Exact fractions
check every dual inequality and reconstruct every normalized lower bound.
Apache-2.0; substantial OpenAI assistance.
"""
from fractions import Fraction as Q
from hashlib import sha256
from itertools import combinations_with_replacement,product
from pathlib import Path
import importlib.util
import json

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
PRICE = REPO/'research/kappa-next-regime/width-search/review_invoice_outer.py'
spec = importlib.util.spec_from_file_location('saved_dual_price',PRICE)
price = importlib.util.module_from_spec(spec); spec.loader.exec_module(price)


def main():
    widths = (4,5,6,7,8,9)
    inventory = (26,2,18,53,96,213)
    all_patterns = []
    for pattern in product(*(range(48//w+1) for w in widths)):
        used = sum(w*n for w,n in zip(widths,pattern))
        if used <= 48:
            all_patterns.append((pattern,used))
    expected_partitions = {ds for ds in combinations_with_replacement(range(1,7),9) if sum(ds) == 27}
    receipts = [HERE/'COMPLEX-CLOCK-PACKING.json',HERE/'COMPLEX-CLOCK-CEILING.json']
    summaries = []
    for path in receipts:
        data = json.loads(path.read_text())
        for source,digest in data['source_sha256'].items():
            assert sha256((REPO/source).read_bytes()).hexdigest() == digest
        assert data['m'] == 73 and data['W_per_replica'] == 896
        assert {int(w):n for w,n in data['width_inventory'].items()} == dict(zip(widths,inventory))
        a = Q(data['parameter']); H = {0:Q(0)}
        for r in range(1,49):
            lo,hi = price.log_interval(Q(73,r)); H[r] = r*price.exp_interval(a*lo,a*hi)[0]
        local = {int(r):n for r,n in data['local_profile'].items()}
        assert local == {1:2439,2:724,3:225,4:102,5:20,8:8}
        local_lower = 9*sum(n*H[r] for r,n in local.items())
        observed = set(); checks = 0; wrong_slot_control = False
        for row in data['rows']:
            ds = tuple(row['partition']); observed.add(ds)
            helper = tuple(map(Q,row['helper_dual']))
            slots = {int(d):Q(z) for d,z in row['slot_dual'].items()}
            assert set(slots) == set(range(1,7)) and len(helper) == 6
            for delta in range(1,7):
                found_tight = False
                for pattern,used in all_patterns:
                    if used > 8*delta:
                        continue
                    checks += 1
                    total = slots[delta]+sum(n*y for n,y in zip(pattern,helper))
                    assert total <= H[8*delta-used], 'invalid saved dual inequality'
                    if total == H[8*delta-used]:
                        found_tight = True
                        assert total+1 > H[8*delta-used]
                        wrong_slot_control = True
                assert found_tight, 'slot dual is the exact minimum claimed by the constructor'
            idle_lower = sum(9*n*y for n,y in zip(inventory,helper))+224*sum(slots[d] for d in ds)
            moment_lower = (local_lower+idle_lower)/(73*896)
            assert str(idle_lower) == row['idle_tariff_lower']
            assert str(moment_lower) == row['normalized_moment_lower']
            assert str(moment_lower-1) == row['normalized_moment_minus_one_lower']
            assert moment_lower > 1
        assert observed == expected_partitions and len(data['rows']) == 88
        assert checks == data['all_pattern_constraints_checked'] == 322344
        assert wrong_slot_control
        summaries.append({'receipt':path.name,'parameter':str(a),'partitions_checked':88,
                          'exact_inequalities_checked':checks,'all_reject':True,
                          'inflated_slot_dual_control_rejected':True,
                          'minimum_normalized_excess':str(min(Q(row['normalized_moment_minus_one_lower']) for row in data['rows']))})
    out = {'status':'INDEPENDENT_STANDARD_LIBRARY_SAVED_PACKING_DUAL_CHECK_PASS',
           'receipts':summaries,'scope':'Verifies the numerical-independent dual certificates and stated packing relaxation. Does not supply a controller, an integer lift, frame projectors, or owner admission.',
           'source_sha256':{str(p.relative_to(REPO)):sha256(p.read_bytes()).hexdigest() for p in receipts+[PRICE,Path(__file__)]}}
    (HERE/'PACKING-DUALS-CHECK.json').write_text(json.dumps(out,sort_keys=True,indent=2)+'\n')
    print(out['status'],sum(row['exact_inequalities_checked'] for row in summaries),'inequalities')


if __name__ == '__main__':
    main()
