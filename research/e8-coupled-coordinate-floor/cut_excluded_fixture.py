"""Independent cut-excluded partial-quotient fixture, by conorholds.

Apache-2.0; substantial OpenAI Codex assistance. Reuses only the independent
partial fixture/model. Left normalization is stable; right normalization
merges the repeated b reader and lowers the actual P rank to eight.
"""

from fractions import Fraction
from pathlib import Path
import json
import runpy


PARTIAL = runpy.run_path(str(Path(__file__).with_name("partial_fixture.py")),
                        run_name="partial_fixture")
M = PARTIAL["M"]
Field, require = M["Field"], M["require"]


def choose_pivot(rows, labels, selected):
    span = [labels[i] for i in selected]
    rank = M["binary_rank"](span)
    for v, label in enumerate(labels):
        pairings = [(label & labels[i]).bit_count() % 2 for i in selected]
        if (M["binary_rank"](span + [label]) == rank + 1
                and pairings[5:] == [0, 0] and any(pairings[:5])):
            require(any(M["dot"](rows[v], rows[i]) == 0 for i in selected[:5]),
                    "some J root is scalar orthogonal to the pivot")
            return v, pairings
    raise ValueError("no cut-excluded pivot with free b and a nonneighbor J")


def verify_field(rows, labels, selected, v, h, dual, field):
    evaluate = PARTIAL["evaluate"]
    units = [tuple(field.scalar(int(i == a)) for i in range(120)) for a in selected]
    pivot = tuple(field.scalar(int(i == v)) for i in range(120))
    q = field.combine(*((1, unit) for unit in units[:6]))
    b = field.combine((1, units[5]), (1, units[6]))
    q_minus_b = field.combine((1, q), (-1, b))
    code_h = [evaluate(rows, normal, field) for normal in h]
    t = [field.combine((Fraction(1, 2), evaluate(rows, normal, field))) for normal in dual]
    high_q = [field.combine((1, code_h[j]), (-2, q_minus_b)) for j in range(5)]
    high_q += [field.combine((1, code_h[j]), (-2, b)) for j in (5, 6)] + [code_h[7]]
    low_q = field.combine(*((2, vector) for vector in t[:5]))
    low_b = field.combine(*((-2, vector) for vector in t[:5]), (2, t[5]), (2, t[6]))
    left = [low_q, field.combine((1, low_b), (-1, pivot))] + t + [pivot]
    right = [q, b] + high_q + [b]
    require(M["product_equal"](left, right, rows, field), "exact cut-excluded decoder product")
    require(all(any(vector) for vector in left + right), "all factors active")
    require(len({field.ray(vector) for vector in left}) == 11,
            "left normalization is stable")
    require(len({field.ray(vector) for vector in right}) == 10 and right[1] == right[10],
            "right b readers genuinely repeat")
    require((field.rank(left), field.rank(right)) == (9, 10), "actual ranks nine and ten")
    require(field.rank(left + code_h + [pivot]) == 9, "actual singleton P space")
    require(field.rank(right + code_h + [q, b]) == 10, "actual Q equals C plus D prime")
    require(field.rank(right[:-1]) == 10, "nonpivot Q columns form an actual basis")
    p_weights = [M["support_weight"](vector, labels) for vector in left]
    q_weights = [M["support_weight"](vector, labels) for vector in right]
    costs = [M["term_cost"](p, r, labels) for p, r in zip(left, right)]
    require(p_weights == [9] * 10 + [1], "actual singleton support weights")
    require(q_weights == [5, 2] + [8] * 7 + [9, 2], "actual partial Q support weights")
    require(costs == [5, 2] + [8] * 7 + [9, 0] and sum(costs) == 72,
            "cut-excluded COPY equality profile")
    b_normal = tuple(-sum(dual[j][i] for j in range(5)) + dual[5][i] + dual[6][i]
                     for i in range(8))
    require(field.rank([b_normal, tuple(Fraction(x, 2) for x in rows[v])]) == 2,
            "mixed low P normal is not the pivot root direction")
    coordinates = [i for i, label in enumerate(labels)
                   if (label & labels[v]).bit_count() % 2]
    require(any(q[i] for i in coordinates) and all(not b[i] for i in coordinates),
            "quotient is not supported entirely on pivot neighbors")
    restricted = [tuple(vector[i] for i in coordinates) for vector in right[:-1]]
    require(field.rank(restricted) == 9 and sum(not any(vector) for vector in restricted) == 1,
            "actual partial-basis cut kernel is generated by b")
    quotient = PARTIAL["quotient_audit"](q, b, units, labels, field)
    # The right merge combines (L_b-delta_v,b) and (delta_v,b).
    right_merged_p = [low_q, low_b] + t
    right_merged_q = [q, b] + high_q
    require(M["product_equal"](right_merged_p, right_merged_q, rows, field),
            "right merge preserves exactness")
    require((field.rank(right_merged_p), field.rank(right_merged_q)) == (8, 10),
            "right merge really lowers the P rank")
    require(M["normalized"](right_merged_p, right_merged_q, field),
            "merged fixture is normalized on both sides")
    merged_p, merged_q = M["merge"](left, right, field)
    require((len(merged_p), field.rank(merged_p), field.rank(merged_q)) == (10, 8, 10),
            "independent alternating normalizer agrees with the rank drop")
    require(M["product_equal"](merged_p, merged_q, rows, field), "full merge exactness")
    merged_costs = [M["term_cost"](p, r, labels) for p, r in zip(merged_p, merged_q)]
    require(sorted(merged_costs) == sorted(costs[:-1]) and sum(merged_costs) == 72,
            "merge preserves the linear bill")
    require(not M["product_equal"](left[:-1], right[:-1], rows, field),
            "active free pivot cannot be deleted")
    wrong_shift = list(left)
    wrong_shift[1] = low_b
    require(not M["product_equal"](wrong_shift, right, rows, field),
            "missing singleton compensation fails")
    wrong_reader = list(right)
    wrong_reader[-1] = q
    require(not M["product_equal"](left, wrong_reader, rows, field),
            "incorrect pivot reader fails")
    return {"terms": 11, "actual_ranks": [9, 10], "costs": costs,
            "left_normalization_stable": True, "right_normalization_stable": False,
            "right_merged_terms": 10, "right_merged_ranks": [8, 10],
            "right_merged_copy": 72, "partial_basis_cut_rank": 9,
            "partial_basis_vanishing_columns": 1, "quotient": quotient,
            "failure_controls": 3}


def verify():
    rows, labels = M["root_model"]()
    M["check_model"](rows, labels)
    selected, _, h, dual, determinant, signs = PARTIAL["selected_data"](rows, labels)
    v, pairings = choose_pivot(rows, labels, selected)
    result = {"root_coordinates_A": selected, "root_coordinate_v": v,
              "doubled_pivot_root": rows[v], "pivot_pairings_against_A": pairings,
              "scalar_rank_A": 7, "binary_rank_A": 6,
              "binary_rank_A_plus_pivot": 7, "all_A_are_neighbors": False,
              "gram_pairing_checks": 14400, "fields": {}}
    for prime in (0, 3, 5, 7):
        result["fields"][str(prime) if prime else "Q"] = verify_field(
            rows, labels, selected, v, h, dual, Field(prime))
    return result


if __name__ == "__main__":
    print(json.dumps(verify(), indent=2, sort_keys=True))
