HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LOADER = "research/centre-block-moore-bound/verify.py"
TRIPLE = (0, 6, 85)
CENSUS_CAP = 4080
ACTIVE = 17


def require(ok, message):
    if not ok:
        raise ValueError(message)


def digest(value):
    return sha256(json.dumps(value, separators=(",", ":")).encode()).hexdigest()


def authenticate(root=ROOT):
    """Check every declared live input before executing retained source."""
    rows = json.loads((HERE / "SOURCES.json").read_bytes())["files"]
    inputs = {}
    for row in rows:
        if row["usage"] != "input":
            continue
        path = root / row["path"]
        require(path.is_file() and not path.is_symlink(), "regular source: " + row["path"])
        raw = path.read_bytes()
        require(sha256(raw).hexdigest() == row["sha256"], "source SHA256: " + row["path"])
        inputs[row["path"]] = raw
    require(LOADER in inputs, "loader is a pinned input")
    return inputs


def load(root=ROOT):
    raw = authenticate(root)[LOADER]
    module = types.ModuleType("retained_centre_block_moore_bound")
    module.__file__ = str(root / LOADER)
    exec(compile(raw, module.__file__, "exec"), module.__dict__)
    # The retained loader authenticates its own closure and checks rank R = 8,
    # H = R/4, nonparallel columns and unique ordered route products.
    _, _, rows, routes, _ = module.load_sources(root)
    return rows, routes


def primitive(column):
    denominator = lcm(*(x.denominator for x in column))
    values = [int(x * denominator) for x in column]
    divisor = 0
    for value in values:
        divisor = gcd(divisor, value)
    return tuple(value // divisor for value in values)


def apply(columns, vector):
    out = 0
    while vector:
        low = vector & -vector
        out ^= columns[low.bit_length() - 1]
        vector ^= low
    return out


def compose(a, b):
    """Matrix product a*b over F2, both given by their binary columns."""
    return tuple(apply(a, column) for column in b)


def closure(generators, cap=None):
    """Group generated by `generators` (left multiplication); None above cap."""
    identity = tuple(1 << k for k in range(len(generators[0])))
    seen, frontier = {identity}, [identity]
    while frontier:
        nxt = []
        for g in frontier:
            for s in generators:
                h = compose(s, g)
                if h not in seen:
                    seen.add(h)
                    nxt.append(h)
                    if cap is not None and len(seen) > cap:
                        return None
        frontier = nxt
    return seen


def active_part(route):
    """Routes fix spectators 17..72 and keep the active block invariant."""
    require(all(route[k] == 1 << k for k in range(ACTIVE, len(route))), "spectators fixed")
    require(all(route[k] >> ACTIVE == 0 for k in range(ACTIVE)), "active block invariant")
    return route[:ACTIVE]


def kernel_coefficients(rows, triple):
    a, b, c = triple
    col = [[rows[k][p] for k in range(8)] for p in triple]
    i, j = next((i, j) for i, j in combinations(range(8), 2)
                if col[0][i] * col[1][j] != col[0][j] * col[1][i])
    det = col[0][i] * col[1][j] - col[0][j] * col[1][i]
    u = {a: (col[2][i] * col[1][j] - col[2][j] * col[1][i]) / det,
         b: (col[0][i] * col[2][j] - col[0][j] * col[2][i]) / det,
         c: Fraction(-1)}
    require(all(sum(u[p] * rows[k][p] for p in u) == 0 for k in range(8)), "R u = 0")
    return u


def residuals(rows, routes, x, ports):
    """Count owners with R x(g) != 0 and outputs with T x(d) != 0 (T = R/4 routed)."""
    owners = {g for g, _ in x}
    bad_s = sum(any(sum(rows[k][p] * x.get((g, p), 0) for p in ports) != 0 for k in range(8))
                for g in owners)
    outputs = {compose(g, routes[p]) for g, p in x}
    bad_t = 0
    for d in outputs:
        incoming = {p: x.get((compose(d, routes[p]), p), 0) for p in ports}
        if any(sum(rows[k][p] / 4 * incoming[p] for p in ports) != 0 for k in range(8)):
            bad_t += 1
    return bad_s, bad_t, len(outputs)


def dependent_triples(rows):
    columns = [primitive([rows[k][p] for k in range(8)]) for p in range(112)]
    out = []
    for a, b in combinations(range(112), 2):
        x, y = columns[a], columns[b]
        i, j = next((i, j) for i, j in combinations(range(8), 2) if x[i] * y[j] != x[j] * y[i])
        det = x[i] * y[j] - x[j] * y[i]
        for c in range(b + 1, 112):
            z = columns[c]
            u, v = z[i] * y[j] - z[j] * y[i], x[i] * z[j] - x[j] * z[i]
            if all(u * xx + v * yy == det * zz for xx, yy, zz in zip(x, y, z)):
                out.append((a, b, c))
    return out


def build(root=ROOT):
    rows, routes = load(root)
    active = [active_part(r) for r in routes]
    a, b, c = TRIPLE
    u = kernel_coefficients(rows, TRIPLE)

    # Even subgroup and full subgroup, on the complete 73-dimensional routes.
    even = closure([compose(routes[a], routes[b]), compose(routes[b], routes[c])])
    full = closure([routes[a], routes[b], routes[c]])
    require(len(even) == 4080 and len(full) == 8160, "|K+| = 4080, |K| = 8160")
    require(routes[a] not in even and all(routes[p] not in full for p in range(112)
                                          if p not in TRIPLE), "only the triple's ports lie in K")
    require(len(closure([compose(s, t) for s, t in
                         ((active[a], active[b]), (active[b], active[c]))])) == 4080,
            "active-block restriction is faithful on K+")

    x = {(g, p): u[p] for g in even for p in TRIPLE}
    bad_s, bad_t, outputs = residuals(rows, routes, x, TRIPLE)
    require(bad_s == 0 and bad_t == 0 and outputs == 4080, "Sx = 0 and Tx = 0 everywhere")

    # Controls: each must break the kernel identity.
    drop = next(iter(sorted(even)))
    truncated = {k: v for k, v in x.items() if k[0] != drop}
    t_s, t_t, _ = residuals(rows, routes, truncated, TRIPLE)
    require(t_s == 0 and t_t == 3, "removing one owner leaves exactly three nonzero outputs")
    skew = dict(x)
    skew[(drop, c)] = Fraction(-2)
    k_s, _, _ = residuals(rows, routes, skew, TRIPLE)
    require(k_s == 1, "a changed coefficient violates Sx = 0 at that owner")
    other = next(g for g in full if g not in even)
    shifted = {(compose(other, g), p): v for (g, p), v in x.items()}
    o_s, o_t, _ = residuals(rows, routes, shifted, TRIPLE)
    require(o_s == 0 and o_t == 0, "the other left coset of K+ is also a kernel support")

    # Census: every dependent triple's even subgroup has order 4080 or exceeds it.
    triples = dependent_triples(rows)
    require(len(triples) == 896, "896 dependent column triples")
    orders = Counter()
    small = []
    for t in triples:
        gens = [compose(active[t[0]], active[t[1]]), compose(active[t[1]], active[t[2]])]
        group = closure(gens, cap=CENSUS_CAP)
        if group is None:
            orders["gt_4080"] += 1
        else:
            orders[str(len(group))] += 1
            small.append(list(t))
    require(orders == Counter({"4080": 56, "gt_4080": 840}), "dependent-triple even-subgroup census")
    require(list(TRIPLE) in small, "witness triple is extremal in the census")

    return {"schema_version": 1,
            "claim": "explicit_selected_centre_common_kernel_vector_on_4080_owners",
            "witness": {"ports": list(TRIPLE),
                        "coefficients": {str(p): str(u[p]) for p in TRIPLE},
                        "primitive_columns": [list(primitive([rows[k][p] for k in range(8)]))
                                              for p in TRIPLE],
                        "even_subgroup_order": 4080, "subgroup_order": 8160,
                        "support_owners": 4080, "outputs_checked": outputs,
                        "nonzero_S_owners": 0, "nonzero_T_outputs": 0,
                        "support_sha256": digest(sorted(list(g) for g in even))},
            "repair_bound_at_block": {"block_owners": 4080,
                                      "floor_104B": 104 * 4080,
                                      "common_kernel_dimension_at_least": 1},
            "controls": {"drop_one_owner_nonzero_T_outputs": t_t,
                         "changed_coefficient_nonzero_S_owners": k_s,
                         "other_coset_is_kernel": True},
            "dependent_triple_census": {"dependent_triples": 896,
                                        "even_subgroup_orders": dict(sorted(orders.items())),
                                        "order_4080_triples_sha256": digest(small)},
            "lower_bound_reference": "research/centre-block-moore-bound: support >= 15",
            "no_new_kappa": True}


