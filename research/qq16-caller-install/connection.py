from pathlib import Path
import gzip,json
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]

def bindings():
    # Authentication is repeated even when the caller already joined the cohort.
    import qq16_auth as A
    import runtime
    A.authenticate()
    from selected_source import load
    from selected_binding import SelectedBinding,Group,embed,literal
    from native_program import compile_local
    from scalar_program import ScalarProgram
    data=load()
    packet=A.parse(gzip.decompress((ROOT/'research/joint-query/certificate.json.gz').read_bytes()))
    word=A.parse((HERE/'inputs/PR4106-WORD.json').read_bytes())
    P=runtime.module('qq16_producer',HERE/'producer.py')
    D=runtime.module('qq16_decoder',HERE/'decoder.py')
    C=runtime.module('qq16_signed',HERE/'inputs/PR4129-construction.py')
    L=runtime.module('qq16_line_source',ROOT/'research/qq16-line-normalized-decoder/verify.py')
    algebra,R,routes,labels,pins=L.load_source()
    maps=D.finite_maps(word,algebra,routes,labels,L.bridge)
    parent=P.ProducerBinding(data,packet,SelectedBinding,Group,compile_local,embed,literal,ScalarProgram)
    service=D.DecoderBinding(word,data['phases'],maps,parent.cover,Group,literal,
                            ScalarProgram,C.signed_recipe,P.map_group,P.order)
    return data,packet,word,parent,service

def install(root_layer, producer_binding, service_binding, ordinary_factory, adopt=True):
    """Compile before input; create two distinct paid Ordinary backends.

    `root_layer` is the actual original RootLayer. Its original exact C Machine
    is retained and used sequentially by producer and service. `ordinary_factory`
    must construct admitted source Ordinary instances, not endpoint doubles.
    Runtime descriptors are generated by Installation, never by this factory.
    """
    import runtime
    from machine import Machine,transfer
    from cardinal_counts import Count
    from session import erase_marker
    I=runtime.module('qq16_installer',HERE/'installer.py')
    P=runtime.module('qq16_packet',HERE/'packet.py')
    S=runtime.module('qq16_lifecycle',HERE/'lifecycle.py')
    from qq16_producer import machine_class
    from qq16_decoder import ServiceBank
    cls=machine_class(Machine,Count,transfer,erase_marker)
    original=root_layer.machine
    producer_native,service_native=ordinary_factory(),ordinary_factory()
    I.need(len({id(original.monomial.compact.binary.native),id(producer_native),id(service_native)})==3,
           'three distinct admitted Ordinary inventories')
    parent=cls(producer_binding,producer_native,producer_binding.catalogue,original)
    service=cls(service_binding,service_native,service_binding.catalogue,original)
    installation=I.Installation(producer_binding,service,original,
                      P.PacketCompiler,S.CallerStorage,ServiceBank,
                      fields=2*service_binding.ports,adopt=adopt)
    parent.at_fence=installation
    I.attach_root(root_layer,parent)
    return installation
